#!/usr/bin/env python3
# Generates tables.c of this directory: the runes for which the unicode predicates and
# strconv.IsPrint/IsGraphic of an older Go release give another answer than those of the newest
# release the port implements (unicode/tables.c, strconv/isprint.c). The port computes the newest
# answer and flips it inside these ranges. Dev-only; no Go toolchain needed:
#
#	python3 -I mkdiff.py <go1.26.5>/src <go1.27.1>/src go1.26.5 go1.27.1 > tables.c
#
# Copyright 2009 The Go Authors. All rights reserved. BSD-3-Clause (see LICENSE in Go).
import re
import sys

# The predicates of unicode.c (go_std_release.unicode order) and the tables they test for runes
# above MaxLatin1 (IsControl has no table: all control characters are Latin-1).
PREDICATES = [
    ("Letter", ["_L"]), ("Digit", ["_Nd"]), ("Upper", ["_Lu"]), ("Lower", ["_Ll"]),
    ("Space", ["_White_Space"]), ("Punct", ["_P"]), ("Graphic", ["_L", "_M", "_N", "_P", "_S", "_Zs"]),
    ("Print", ["_L", "_M", "_N", "_P", "_S"]), ("Mark", ["_M"]), ("Number", ["_N"]), ("Symbol", ["_S"]),
]
PER_LINE = 4


def ranges_of(src, name):
    m = re.search(r"^var " + re.escape(name) + r" = &RangeTable\{\n(.*?)^\}\n", src, re.M | re.S)
    if not m:
        sys.exit("table %s not found" % name)
    s = set()
    for lo, hi, st in re.findall(r"\{(0x[0-9a-f]+), (0x[0-9a-f]+), (\d+)\}", m.group(1)):
        s.update(range(int(lo, 16), int(hi, 16) + 1, int(st)))
    return s


def properties(src):
    m = re.search(r"^var properties = \[MaxLatin1 \+ 1\]uint8\{\n(.*?)^\}\n", src, re.M | re.S)
    return m.group(1)


def isprint(src):
    """The runes strconv.IsPrint accepts above Latin-1, and the isGraphic list."""
    def arr(name):
        m = re.search(r"^var " + name + r" = \[\](?:uint16|uint32)\{[^\n]*\n(.*?)^\}\n", src, re.M | re.S)
        if not m:
            sys.exit("table %s not found" % name)
        return [int(v, 16) for v in re.findall(r"0x([0-9a-f]+)", m.group(1))]
    p16, np16, p32, np32, graphic = (arr(n) for n in
                                     ("isPrint16", "isNotPrint16", "isPrint32", "isNotPrint32", "isGraphic"))
    s = set()
    for i in range(0, len(p16), 2):
        s.update(range(p16[i], p16[i + 1] + 1))
    s.difference_update(np16)
    for i in range(0, len(p32), 2):
        s.update(range(p32[i], p32[i + 1] + 1))
    s.difference_update(v + 0x10000 for v in np32)
    return {r for r in s if r > 0xFF}, set(graphic)


def to_ranges(s):
    out = []
    for r in sorted(s):
        if out and out[-1][1] == r - 1:
            out[-1][1] = r
        else:
            out.append([r, r])
    return out


def emit(w, cname, rs):
    w("static const uint32_t %s[] = {\n" % cname)
    for i in range(0, len(rs), PER_LINE):
        w("\t" + " ".join("0x%05x, 0x%05x," % (lo, hi) for lo, hi in rs[i:i + PER_LINE]) + "\n")
    w("};\n")


def main():
    if len(sys.argv) != 5:
        sys.exit("usage: mkdiff.py <old go>/src <new go>/src <old version> <new version>")
    old_dir, new_dir, old_v, new_v = sys.argv[1:]
    read = lambda d, f: open("%s/%s" % (d, f), encoding="utf-8").read()
    old_u, new_u = read(old_dir, "unicode/tables.go"), read(new_dir, "unicode/tables.go")
    if properties(old_u) != properties(new_u):
        sys.exit("Latin-1 properties differ: not supported by the diff")
    out = []
    w = out.append
    w("/* Code generated by mkdiff.py from %s and %s src/unicode/tables.go and src/strconv/isprint.go;\n"
      " * DO NOT EDIT. The runes above U+00FF for which the predicate of %s answers differently from\n"
      " * that of %s, as sorted [lo, hi] pairs. Copyright 2009 The Go Authors. All rights reserved.\n"
      " * BSD-3-Clause (see LICENSE in Go). */\n" % (old_v, new_v, old_v, new_v))
    names = []
    seen = {}  # identical lists are emitted once

    def add(cname, rs):
        key = tuple(map(tuple, rs))
        if rs and key not in seen:
            seen[key] = cname
            w("\n")
            emit(w, cname, rs)
        names.append((seen.get(key), len(rs)))

    for pred, tables in PREDICATES:
        so = set().union(*(ranges_of(old_u, t) for t in tables))
        sn = set().union(*(ranges_of(new_u, t) for t in tables))
        add("go_std_diff_Is" + pred, to_ranges({r for r in so ^ sn if r > 0xFF}))
    po, go = isprint(read(old_dir, "strconv/isprint.go"))
    pn, gn = isprint(read(new_dir, "strconv/isprint.go"))
    for cname, s in (("go_std_diff_strconvIsPrint", po ^ pn), ("go_std_diff_strconvIsGraphic", go ^ gn)):
        add(cname, to_ranges(s))
    w("\n/* go_std_release.unicode (unicode.IsLetter, ..., unicode.IsSymbol), .strconv_isprint and\n"
      " * .strconv_isgraphic */\n")
    ent = ["{%s, %d}" % (cname if n else "NULL", n) for cname, n in names]
    w("#define GO_STD_DIFF_UNICODE \\\n\t{%s}\n" % ", \\\n\t ".join(ent[:-2]))
    w("#define GO_STD_DIFF_STRCONV_ISPRINT %s\n" % ent[-2])
    w("#define GO_STD_DIFF_STRCONV_ISGRAPHIC %s\n" % ent[-1])
    sys.stdout.write("".join(out))


main()
