#!/usr/bin/env python3
# Generates isprint.c (the tables of strconv.IsPrint/IsGraphic) from Go's src/strconv/isprint.go.
# Dev-only; no Go toolchain needed:
#
#	python3 -I mkisprint.py <go1.26.5>/src/strconv/isprint.go > isprint.c
#
# Copyright 2013 The Go Authors. All rights reserved. BSD-3-Clause (see LICENSE in Go).
import re
import sys

TABLES = ["isPrint16", "isNotPrint16", "isPrint32", "isNotPrint32", "isGraphic"]
PER_LINE = 8


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: mkisprint.py <go>/src/strconv/isprint.go")
    with open(sys.argv[1], encoding="utf-8") as f:
        src = f.read()
    out = []
    w = out.append
    w("/* Code generated by mkisprint.py from go1.26.5 src/strconv/isprint.go; DO NOT EDIT.\n"
      " * Copyright 2013 The Go Authors. All rights reserved. BSD-3-Clause (see LICENSE in Go). */\n")
    w('#include "../internal.h"\n')
    for name in TABLES:
        m = re.search(r"^((?://[^\n]*\n)*)var " + name + r" = \[\](uint16|uint32)\{([^\n]*)\n(.*?)^\}\n",
                      src, re.M | re.S)
        if not m:
            sys.exit("table %s not found" % name)
        comment, typ, trailing, body = m.groups()
        vals = [int(v, 16) for v in re.findall(r"0x([0-9a-f]+)", body)]
        width = 8 if typ == "uint32" and max(vals) > 0xffff else 4
        w("\n")
        for line in comment.splitlines():
            w("/* %s */\n" % line[2:].strip())
        note = trailing.strip()
        if note.startswith("//"):
            w("/* %s */\n" % note[2:].strip())
        w("static const %s_t strconv_%s[] = {\n" % (typ, name))
        for i in range(0, len(vals), PER_LINE):
            w("\t" + " ".join("0x%0*x," % (width, v) for v in vals[i:i + PER_LINE]) + "\n")
        w("};\n")
    sys.stdout.write("".join(out))


main()
