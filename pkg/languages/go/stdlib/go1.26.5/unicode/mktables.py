#!/usr/bin/env python3
# Generates tables.c (the range tables used by unicode.c) from Go's src/unicode/tables.go.
# Dev-only; no Go toolchain needed:
#
#	python3 -I mktables.py <go1.26.5>/src/unicode/tables.go > tables.c
#
# Copyright 2009 The Go Authors. All rights reserved. BSD-3-Clause (see LICENSE in Go).
import re
import sys

# Go table variable -> the names Go's exported variables use for it (letter.go/graphic.go).
TABLES = ["_L", "_Ll", "_Lu", "_M", "_N", "_Nd", "_P", "_S", "_Zs", "_White_Space"]
ALIASES = [
    ("Letter", "_L"), ("L", "_L"), ("Lower", "_Ll"), ("Ll", "_Ll"), ("Upper", "_Lu"), ("Lu", "_Lu"),
    ("Mark", "_M"), ("M", "_M"), ("Number", "_N"), ("N", "_N"), ("Digit", "_Nd"), ("Nd", "_Nd"),
    ("Punct", "_P"), ("P", "_P"), ("Symbol", "_S"), ("S", "_S"), ("Zs", "_Zs"),
    ("White_Space", "_White_Space"),
]
PER_LINE = 4


def table(src, name):
    m = re.search(r"^var " + re.escape(name) + r" = &RangeTable\{\n(.*?)^\}\n", src, re.M | re.S)
    if not m:
        sys.exit("table %s not found" % name)
    body = m.group(1)
    out = {"R16": [], "R32": [], "LatinOffset": 0}
    for part in ("R16", "R32"):
        pm = re.search(r"\t" + part + r": \[\]Range" + part[1:] + r"\{\n(.*?)\n\t\},", body, re.S)
        if pm:
            for t in re.findall(r"\{(0x[0-9a-f]+), (0x[0-9a-f]+), (\d+)\}", pm.group(1)):
                out[part].append((int(t[0], 16), int(t[1], 16), int(t[2])))
    lm = re.search(r"\tLatinOffset: (\d+),", body)
    if lm:
        out["LatinOffset"] = int(lm.group(1))
    return out


def emit_ranges(w, cname, ctype, ranges, width):
    w("static const %s %s[] = {\n" % (ctype, cname))
    for i in range(0, len(ranges), PER_LINE):
        row = ranges[i:i + PER_LINE]
        w("\t" + " ".join("{0x%0*x, 0x%0*x, %d}," % (width, lo, width, hi, st) for lo, hi, st in row) + "\n")
    w("};\n")


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: mktables.py <go>/src/unicode/tables.go")
    with open(sys.argv[1], encoding="utf-8") as f:
        src = f.read()
    version = re.search(r'^const Version = "([^"]+)"', src, re.M).group(1)
    out = []
    w = out.append
    w("/* Code generated by mktables.py from go1.26.5 src/unicode/tables.go (Unicode %s); DO NOT EDIT.\n"
      " * Only the tables used by unicode.c. Copyright 2009 The Go Authors. All rights reserved.\n"
      " * BSD-3-Clause (see LICENSE in Go). */\n" % version)
    w('#include "../internal.h"\n\n')
    w("/* Range16, Range32, RangeTable (letter.go); R16/R32 are counted arrays. */\n")
    w("typedef struct {\n\tuint16_t Lo, Hi, Stride;\n} unicode_Range16;\n\n")
    w("typedef struct {\n\tuint32_t Lo, Hi, Stride;\n} unicode_Range32;\n\n")
    w("typedef struct {\n\tconst unicode_Range16 *R16;\n\tint nR16;\n\tconst unicode_Range32 *R32;\n"
      "\tint nR32;\n\tint LatinOffset; /* number of entries in R16 with Hi <= MaxLatin1 */\n"
      "} unicode_RangeTable;\n\n")
    w('#define unicode_Version "%s"\n' % version)
    w("#define unicode_LEN(a) ((int)(sizeof(a) / sizeof *(a)))\n")
    for name in TABLES:
        t = table(src, name)
        c = "unicode_" + name
        w("\n")
        if t["R16"]:
            emit_ranges(w, c + "_R16", "unicode_Range16", t["R16"], 4)
        if t["R32"]:
            emit_ranges(w, c + "_R32", "unicode_Range32", t["R32"], 5)
        r16 = ("%s_R16, unicode_LEN(%s_R16)" % (c, c)) if t["R16"] else "NULL, 0"
        r32 = ("%s_R32, unicode_LEN(%s_R32)" % (c, c)) if t["R32"] else "NULL, 0"
        w("static const unicode_RangeTable %s = {\n\t%s, %s, %d};\n" % (c, r16, r32, t["LatinOffset"]))
    w("\n/* These variables have type *RangeTable. */\n")
    for alias, name in ALIASES:
        w("#define unicode_%s (&unicode_%s)\n" % (alias, name))

    # properties: [MaxLatin1 + 1]uint8 with symbolic values (graphic.go constants).
    m = re.search(r"^var properties = \[MaxLatin1 \+ 1\]uint8\{\n(.*?)^\}\n", src, re.M | re.S)
    props = {}
    for idx, val in re.findall(r"^\t0x([0-9A-F]{2}): ([^,]+),", m.group(1), re.M):
        props[int(idx, 16)] = val.strip()
    w("\n/* Bit masks for each code point under U+0100, for fast lookup (graphic.go). */\n")
    w("enum {\n")
    consts = ["pC", "pP", "pN", "pS", "pZ", "pLu", "pLl", "pp"]
    for i, n in enumerate(consts):
        w("\tunicode_%s = 1 << %d,\n" % (n, i))
    w("\tunicode_pg = unicode_pp | unicode_pZ, /* a graphical character according to the Unicode definition */\n")
    w("\tunicode_pLo = unicode_pLl | unicode_pLu, /* a letter that is neither upper nor lower case */\n")
    w("\tunicode_pLmask = unicode_pLo,\n};\n\n")
    w("static const uint8_t unicode_properties[unicode_MaxLatin1 + 1] = {\n")
    for i in range(256):
        if i not in props:
            continue
        expr = " | ".join(p.strip() if p.strip() == "0" else "unicode_" + p.strip() for p in props[i].split("|"))
        w("\t[0x%02X] = %s,\n" % (i, expr))
    w("};\n")
    sys.stdout.write("".join(out))


main()
