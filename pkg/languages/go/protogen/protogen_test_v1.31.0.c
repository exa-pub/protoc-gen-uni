static Str bad_flag(void *ctx, Str name, Str value)
{
	(void)ctx, (void)value;
	return str_eqc(name, "bad") ? STR_LIT("bad flag") : (Str){NULL, 0};
}

static PgPlugin *new_plugin(const char *req, size_t n, const char **err)
{
	PbMsg *r = pg_parse_request((const uint8_t *)req, n, err);
	if (!r)
		return NULL;
	PgOptions opts = {0};
	opts.ParamFunc = bad_flag;
	opts.Version = &pg_v1_31_0;
	Str e;
	PgPlugin *gen = pg_options_new(&opts, r, &e);
	*err = gen ? NULL : xstrndup(e.p, e.n);
	return gen;
}

static void test_filedesc(void)
{
	const char *err;
	PgPlugin *gen = new_plugin(req_ok, sizeof req_ok - 1, &err);
	CHECK(gen != NULL);
	if (!gen)
		return;
	/* name, packed, presence, optional keyword, synthetic oneof */
	static const struct {
		const char *name;
		bool packed, presence, optkw, synthetic;
	} want[] = {
		{"nums", true, false, false, false},   {"unpacked", false, false, false, false}, {"strs", false, false, false, false},
		{"opt", false, true, true, true},      {"c1", false, true, false, false},        {"o", false, true, true, false},
		{"r2", false, true, false, false},     {"rep", true, false, false, false},       {"r1", false, true, false, false},
		{"plain", false, false, false, false},
	};
	size_t k = 0;
	for (int i = 0; i < gen->nFiles; i++) {
		PgFile *f = gen->Files[i];
		CHECK(f->Generate);
		for (int j = 0; j < f->Messages[0]->nFields && k < sizeof want / sizeof *want; j++, k++) {
			PgField *fd = f->Messages[0]->Fields[j];
			CHECK_STR(fd->Desc->d.name, want[k].name);
			CHECK(pg_v131_field_is_packed(fd->Desc) == want[k].packed);
			CHECK(pg_v131_field_has_presence(fd->Desc) == want[k].presence);
			CHECK(pg_v131_field_has_optional_keyword(fd->Desc) == want[k].optkw);
			CHECK((fd->Oneof && pg_v131_oneof_is_synthetic(fd->Oneof->Desc)) == want[k].synthetic);
		}
	}
	CHECK(k == sizeof want / sizeof *want);
	const int32_t *nums;
	CHECK(pg_v131_message_required_numbers(gen->Files[0]->Messages[0]->Desc, &nums) == 0);
	CHECK(pg_v131_message_required_numbers(gen->Files[1]->Messages[0]->Desc, &nums) == 2 && nums[0] == 4 && nums[1] == 1);
}

static void test_response(void)
{
	const char *err;
	PgPlugin *gen = new_plugin(req_ok, sizeof req_ok - 1, &err);
	CHECK(gen != NULL);
	if (!gen)
		return;
	gen->SupportedFeatures = 1;
	P(pg_new_generated_file(gen, "x.txt", ""), "hi");
	Buf out = {0};
	pg_plugin_response(gen, &out);
	static const char ok[] = "\x10\x01\x7a\x0c\x0a\x05\x78\x2e\x74\x78\x74\x7a\x03\x68\x69\x0a";
	CHECK_MEM(out.p, out.n, ok, sizeof ok - 1);
	pg_plugin_error(gen, STR_LIT("boom"));
	out.n = 0;
	pg_plugin_response(gen, &out);
	CHECK_MEM(out.p, out.n, "\x0a\x04" "boom", 6); /* no supported_features with an error */
}

