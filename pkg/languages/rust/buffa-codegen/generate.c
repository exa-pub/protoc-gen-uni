static const PbMsg *find_file(const PbMsg *req, const char *name)
{
	int n = pb_count(req, CGR_PROTO_FILE);
	for (int i = 0; i < n; i++) {
		const PbMsg *fd = pb_msg_at(req, CGR_PROTO_FILE, i);
		if (pb_has(fd, FDP_NAME) && str_eq(pb_str(fd, FDP_NAME), name))
			return fd;
	}
	return NULL;
}

#define ALLOW_LINTS                                                                                                   \
	"non_camel_case_types, dead_code, unused_imports, unused_qualifications, clippy::derivable_impls, "          \
	"clippy::match_single_binding, clippy::uninlined_format_args, clippy::doc_lazy_continuation, "               \
	"clippy::module_inception"

/* validate_file */
static void validate_walk(const PbMsg *parent, int field, const char *scope, int depth)
{
	if (depth > 100)
		fail("message nesting too deep");
	Map seen = {0};
	int n = pb_count(parent, field);
	for (int i = 0; i < n; i++) {
		const PbMsg *m = pb_msg_at(parent, field, i);
		const char *name = dname(m);
		const char *fqn = *scope ? xcat(scope, ".", name) : name;
		for (int k = 0; k < n_fields(m); k++) {
			const PbMsg *f = field_at(m, k);
			if (pb_has(f, FD_NAME) && has_prefix(dname(f), "__buffa_"))
				fail("reserved field name '%s' in message '%s': proto field names starting with '__buffa_' conflict with "
				     "buffa's internal fields", dname(f), fqn);
		}
		char *mod = to_snake_case(name);
		if (str_eq(mod, SENTINEL_MOD))
			fail("reserved name '%s' at message '%s': this name is reserved for buffa's generated ancillary types (views, "
			     "oneof enums, extensions). Rename the proto element.", SENTINEL_MOD, fqn);
		const char *ex = map_get(&seen, mod);
		if (ex)
			fail("module name conflict in '%s': messages '%s' and '%s' both produce module '%s'", scope, ex, name, mod);
		map_put(&seen, mod, (void *)name);
		validate_walk(m, DP_NESTED_TYPE, fqn, depth + 1);
	}
}

static void validate_file(const PbMsg *file)
{
	const char *package = pb_str(file, FDP_PACKAGE);
	Vec segs = str_split(package, '.');
	for (int i = 0; i < segs.n; i++)
		if (str_eq(segs.v[i], SENTINEL_MOD))
			fail("reserved name '%s' at package '%s': this name is reserved for buffa's generated ancillary types (views, "
			     "oneof enums, extensions). Rename the proto element.", SENTINEL_MOD, package);
	int n = pb_count(file, FDP_ENUM_TYPE);
	for (int i = 0; i < n; i++) {
		const char *name = dname(pb_msg_at(file, FDP_ENUM_TYPE, i));
		if (str_eq(name, SENTINEL_MOD))
			fail("reserved name '%s' at enum '%s.%s': this name is reserved for buffa's generated ancillary types (views, "
			     "oneof enums, extensions). Rename the proto element.", SENTINEL_MOD, package, name);
	}
	validate_walk(file, FDP_MESSAGE_TYPE, package, 0);
}

static char *proto_path_to_stem(const char *path)
{
	char *s = has_suffix(path, ".proto") ? str_trim_suffix(path, ".proto") : xstrdup(path);
	for (char *p = s; *p; p++)
		if (*p == '/')
			*p = '.';
	return s;
}

char *bc_proto_path_to_stem(const char *proto_path) { return proto_path_to_stem(proto_path); }
char *bc_package_to_filename(const char *package) { return xcat(*package ? package : SENTINEL_MOD, ".rs"); }
char *bc_package_to_mod_filename(const char *package) { return xcat(*package ? package : SENTINEL_MOD, ".mod.rs"); }

static char *format_tokens(Vec *items, const char *source)
{
	PpNode *file = pp_file();
	push_all(file, items);
	char *formatted = pp_unparse(file);
	return xcat("// @generated by buffa-codegen. DO NOT EDIT.\n", *source ? xcat("// source: ", source, "\n") : "", "\n", formatted);
}

typedef struct {
	const char *stem;
	Vec owned, view, lazy_view, oneof, view_oneof, ext;
	Vec root_reexports; /* Reexport * */
} ProtoContent;

static void reflect_reexports(Vec *out, const char *gate);
static void reflect_pool_module(Vec *out, Str fds);

static Reexport *root_reexport(const char *name, const char *path, const char *gate)
{
	return reexport(name, path, NULL, gate);
}

static void generate_proto_content(const char *pkg, const PbMsg *file, Reg *reg, ProtoContent *pc)
{
	memset(pc, 0, sizeof *pc);
	validate_file(file);
	Feat features = feat_for_file(file);
	int n = pb_count(file, FDP_ENUM_TYPE);
	for (int i = 0; i < n; i++) {
		const PbMsg *e = pb_msg_at(file, FDP_ENUM_TYPE, i);
		generate_enum(&pc->owned, e, prefixed_type_name(dname(e)), join_fqn(pkg, dname(e)), features);
	}
	FeatureGates g = gates();
	n = pb_count(file, FDP_MESSAGE_TYPE);
	for (int i = 0; i < n; i++) {
		const PbMsg *m = pb_msg_at(file, FDP_MESSAGE_TYPE, i);
		const char *top = dname(m);
		const char *rust_name = prefixed_type_name(top);
		MsgOut mo;
		generate_message(m, pkg, rust_name, join_fqn(pkg, top), features, &mo);
		vcat(&pc->owned, &mo.owned_top);
		char *mod_name = ctx_nested_module_name(pkg, top);
		char *mod_ident = make_field_ident(mod_name);
		for (int k = 0; k < mo.reg.json_ext.n; k++)
			vec_push(&reg->json_ext, xcat(mod_ident, "::", mo.reg.json_ext.v[k]));
		for (int k = 0; k < mo.reg.text_ext.n; k++)
			vec_push(&reg->text_ext, xcat(mod_ident, "::", mo.reg.text_ext.v[k]));
		vcat(&reg->json_any, &mo.reg.json_any);
		vcat(&reg->text_any, &mo.reg.text_any);
		if (mo.owned_mod.n) {
			PpNode *mod = item_mod_super(mod_ident, &mo.owned_mod);
			if (!str_eq(mod_name, to_snake_case(top)))
				pp_push_attr(mod, doc_attr(xcat("Nested items of `", top,
								"`. The module name carries a trailing `_` to avoid a collision with another "
								"module in this scope (a sub-package or sibling message of the same name). See "
								"buffa#135.")));
			vec_push(&pc->owned, mod);
		}
		vcat(&pc->oneof, &mo.oneof_tree);
		vcat(&pc->view, &mo.view_tree);
		vcat(&pc->lazy_view, &mo.lazy_view_tree);
		vcat(&pc->view_oneof, &mo.view_oneof_tree);
		if (CFG->generate_views) {
			char *v = xcat(rust_name, "View"), *ov = xcat(rust_name, "OwnedView");
			vec_push(&pc->root_reexports, root_reexport(v, xcat("self::" SENTINEL_MOD "::view::", v), g.views));
			vec_push(&pc->root_reexports, root_reexport(ov, xcat("self::" SENTINEL_MOD "::view::", ov), g.views));
			if (CFG->lazy_views) {
				char *lv = xcat(rust_name, "LazyView");
				vec_push(&pc->root_reexports, root_reexport(lv, xcat("self::" SENTINEL_MOD "::lazy_view::", lv), g.views));
			}
		}
	}
	Vec exts = {0}, ej = {0}, et = {0};
	n = pb_count(file, FDP_EXTENSION);
	for (int i = 0; i < n; i++)
		vec_push(&exts, (void *)pb_msg_at(file, FDP_EXTENSION, i));
	generate_extensions(&pc->ext, &ej, &et, &exts, pkg, 2, features, pkg);
	for (int k = 0; k < ej.n; k++)
		vec_push(&reg->json_ext, xcat(SENTINEL_MOD "::ext::", ej.v[k]));
	for (int k = 0; k < et.n; k++)
		vec_push(&reg->text_ext, xcat(SENTINEL_MOD "::ext::", et.v[k]));
	for (int i = 0; i < exts.n; i++) {
		char *ci = extension_const_ident(dname(exts.v[i]));
		vec_push(&pc->root_reexports, root_reexport(ci, xcat("self::" SENTINEL_MOD "::ext::", ci), NULL));
	}
	pc->stem = proto_path_to_stem(pb_str(file, FDP_NAME));
}

static Map root_occupied_names(const Vec *files)
{
	Map occ = {0};
	map_put(&occ, SENTINEL_MOD, (void *)1);
	for (int i = 0; i < files->n; i++) {
		const PbMsg *file = files->v[i];
		const char *package = pb_str(file, FDP_PACKAGE);
		int n = pb_count(file, FDP_MESSAGE_TYPE);
		for (int k = 0; k < n; k++) {
			const char *name = dname(pb_msg_at(file, FDP_MESSAGE_TYPE, k));
			map_put(&occ, prefixed_type_name(name), (void *)1);
			map_put(&occ, ctx_nested_module_name(package, name), (void *)1);
		}
		n = pb_count(file, FDP_ENUM_TYPE);
		for (int k = 0; k < n; k++)
			map_put(&occ, prefixed_type_name(dname(pb_msg_at(file, FDP_ENUM_TYPE, k))), (void *)1);
	}
	if (CFG->generate_reflection) {
		map_put(&occ, "descriptor_pool", (void *)1);
		map_put(&occ, "FILE_DESCRIPTOR_SET_BYTES", (void *)1);
	}
	return occ;
}

static bool reg_empty(const Reg *r) { return !r->json_any.n && !r->text_any.n && !r->json_ext.n && !r->text_ext.n; }

static void json_or_text_gates(const char **out, int *n)
{
	FeatureGates g = gates();
	*n = 0;
	if (g.json)
		out[(*n)++] = g.json;
	if (g.text)
		out[(*n)++] = g.text;
}

static void surviving_root_reexports(Vec *out, const Vec *files, const Reg *reg, Vec *cands)
{
	Map occ = root_occupied_names(files);
	if (CFG->emit_register_fn && !reg_empty(reg)) {
		const char *gs[2];
		int ng;
		json_or_text_gates(gs, &ng);
		Reexport *r = xalloc(sizeof *r);
		r->name = "register_types";
		PpNode *u = pp_item_use(PP_VIS_PUB, pp_use_tree("self::" SENTINEL_MOD "::register_types"), false);
		pp_push_attr(u, attr_src("doc", "inline"));
		Vec one_ = one(u);
		cfg_block_any(&r->items, &one_, gs, ng);
		vec_push(cands, r);
	}
	emit_surviving_reexports(out, cands, &occ);
}


static void reg_stmts(PpNode *block, const Vec *paths, const char *method, const char *gate)
{
	for (int i = 0; i < paths->n; i++) {
		PpNode *s = s_semi(e_meth1(pp_e("reg"), method, pp_e(xcat("super::", paths->v[i]))));
		if (gate)
			prepend_attr(s->a, cfg_feature_attr(gate)); /* #[cfg] on the statement's expression */
		pp_push(block, s);
	}
}

static char *generate_package_mod(const char *pkg, ProtoContent *sec, const Reg *reg, Vec *root_reexports, Str fds)
{
	FeatureGates g = gates();
	Vec view_mod = {0}, lazy_view_mod = {0}, oneof_mod = {0}, ext_mod = {0}, register_fn = {0}, reflect_mod = {0};
	if (CFG->generate_views && sec->view.n) {
		Vec inner = {0};
		vcat(&inner, &sec->view);
		if (sec->view_oneof.n)
			vec_push(&inner, item_mod_super("oneof", &sec->view_oneof));
		Vec one_ = one(item_mod_super("view", &inner));
		cfg_block(&view_mod, &one_, g.views);
	}
	if (sec->lazy_view.n) {
		Vec one_ = one(item_mod_super("lazy_view", &sec->lazy_view));
		cfg_block(&lazy_view_mod, &one_, g.views);
	}
	if (sec->oneof.n)
		vec_push(&oneof_mod, item_mod_super("oneof", &sec->oneof));
	if (sec->ext.n)
		vec_push(&ext_mod, item_mod_super("ext", &sec->ext));
	if (CFG->emit_register_fn && !reg_empty(reg)) {
		PpNode *sig = pp_sig("register_types", NULL);
		pp_push(sig, arg("reg", ty_ref_mut(pp_ty("::buffa::type_registry::TypeRegistry"))));
		PpNode *body = pp_block(NULL);
		reg_stmts(body, &reg->json_any, "register_json_any", g.json);
		reg_stmts(body, &reg->json_ext, "register_json_ext", g.json);
		reg_stmts(body, &reg->text_any, "register_text_any", g.text);
		reg_stmts(body, &reg->text_ext, "register_text_ext", g.text);
		PpNode *fn = pp_item_fn(PP_VIS_PUB, sig, body);
		pp_push_attr(fn, doc_attr(" Register this package's `Any` type entries and extension entries."));
		if (CFG->gate_impls_on_crate_features)
			pp_push_attr(fn, attr_src("allow", "unused_variables"));
		const char *gs[2];
		int ng;
		json_or_text_gates(gs, &ng);
		Vec one_ = one(fn);
		cfg_block_any(&register_fn, &one_, gs, ng);
	}
	Vec reflect_reexport = {0};
	if (CFG->generate_reflection) {
		Vec pm = {0};
		if (CFG->shared_descriptor_pool)
			reflect_pool_module_shared(&pm, pkg);
		else
			reflect_pool_module(&pm, fds);
		cfg_block(&reflect_mod, &pm, g.reflect);
		reflect_reexports(&reflect_reexport, g.reflect);
	}
	Vec items = {0};
	/* idiomatic imports: the use block */
	if (cx.imports_phase == IMPORTS_RESOLVING)
		for (int i = 0; i < cx.imports_bindings.n; i++) {
			const char *target = ((char **)cx.imports_bindings.v[i])[1];
			const char *rp = rust_path(target);
			bool lead = rp[0] == ':';
			vec_push(&items, pp_item_use(0, pp_use_tree(lead ? rp + 2 : rp), lead));
		}
	vcat(&items, &sec->owned);
	if (view_mod.n || lazy_view_mod.n || oneof_mod.n || ext_mod.n || register_fn.n || reflect_mod.n) {
		Vec inner = {0};
		vcat(&inner, &view_mod);
		vcat(&inner, &lazy_view_mod);
		vcat(&inner, &oneof_mod);
		vcat(&inner, &ext_mod);
		vcat(&inner, &register_fn);
		vcat(&inner, &reflect_mod);
		PpNode *m = item_mod_super(SENTINEL_MOD, &inner);
		pp_push_attr(m, attr_src("allow", ALLOW_LINTS));
		vec_push(&items, m);
	}
	vcat(&items, &reflect_reexport);
	vcat(&items, root_reexports);
	return format_tokens(&items, "");
}

static void emit_content(Vec *out, const char *pkg, const char *source, const char *stem, const char *suffix, Vec *tokens, Vec *section)
{
	if (!tokens->n)
		return;
	char *name = xcat(stem, suffix, ".rs");
	PpNode *m = pp_macro(pp_path("include"), PP_DELIM_PAREN);
	pp_push(m, pp_tt_lit(pm2_string(str_c(name))));
	vec_push(section, pp_item_macro(m, NULL));
	BcFile *f = xalloc(sizeof *f);
	f->name = name;
	f->content = str_c(format_tokens(tokens, source));
	(void)pkg;
	vec_push(out, f);
}

static void generate_package(const char *pkg, const Vec *files, Str fds, Vec *out)
{
	Reg reg = {0};
	Vec root_reexports = {0};
	if (CFG->idiomatic_imports && CFG->file_per_package) {
		cx.imports_phase = IMPORTS_COLLECTING;
		memset(&cx.imports_collected, 0, sizeof cx.imports_collected);
		memset(&cx.imports_collected_list, 0, sizeof cx.imports_collected_list);
		Reg scratch = {0};
		Map occ = root_occupied_names(files);
		for (int i = 0; i < files->n; i++) {
			ProtoContent pc;
			generate_proto_content(pkg, files->v[i], &scratch, &pc);
			for (int k = 0; k < pc.root_reexports.n; k++)
				map_put(&occ, ((Reexport *)pc.root_reexports.v[k])->name, (void *)1);
		}
		map_put(&occ, "register_types", (void *)1);
		cx.imports_phase = IMPORTS_OFF;
		imports_assign(&occ);
		cx.imports_phase = IMPORTS_RESOLVING;
	}
	ProtoContent sec = {0};
	for (int i = 0; i < files->n; i++) {
		const PbMsg *file = files->v[i];
		ProtoContent pc;
		generate_proto_content(pkg, file, &reg, &pc);
		vcat(&root_reexports, &pc.root_reexports);
		if (CFG->file_per_package) {
			Vec *src[] = {&pc.owned, &pc.view, &pc.lazy_view, &pc.oneof, &pc.view_oneof, &pc.ext};
			Vec *dst[] = {&sec.owned, &sec.view, &sec.lazy_view, &sec.oneof, &sec.view_oneof, &sec.ext};
			for (int k = 0; k < 6; k++)
				vcat(dst[k], src[k]);
		} else {
			const char *source = pb_str(file, FDP_NAME);
			emit_content(out, pkg, source, pc.stem, "", &pc.owned, &sec.owned);
			emit_content(out, pkg, source, pc.stem, ".__view", &pc.view, &sec.view);
			emit_content(out, pkg, source, pc.stem, ".__lazy_view", &pc.lazy_view, &sec.lazy_view);
			emit_content(out, pkg, source, pc.stem, ".__oneof", &pc.oneof, &sec.oneof);
			emit_content(out, pkg, source, pc.stem, ".__view_oneof", &pc.view_oneof, &sec.view_oneof);
			emit_content(out, pkg, source, pc.stem, ".__ext", &pc.ext, &sec.ext);
		}
	}
	Vec reexport_block = {0};
	surviving_root_reexports(&reexport_block, files, &reg, &root_reexports);
	BcFile *f = xalloc(sizeof *f);
	const char *base = *pkg ? pkg : SENTINEL_MOD;
	f->name = CFG->file_per_package ? xcat(base, ".rs") : xcat(base, ".mod.rs");
	f->content = str_c(generate_package_mod(pkg, &sec, &reg, &reexport_block, fds));
	vec_push(out, f);
	cx.imports_phase = IMPORTS_OFF;
}

static Str encode_fds_once(void);

/* validate_shared_root_name: `__buffa_fds` is reserved at the module-tree root */
static void validate_shared_root_name(const Vec *to_generate)
{
	const char *r = "__buffa_fds";
	for (int i = 0; i < cx.n_files; i++) {
		const PbMsg *file = cx.files[i];
		bool gen = false;
		for (int k = 0; k < to_generate->n; k++)
			gen |= str_eq(to_generate->v[k], pb_str(file, FDP_NAME));
		if (!gen)
			continue;
		const char *package = pb_str(file, FDP_PACKAGE);
		Vec segs = str_split(package, '.');
		for (int k = 0; k < segs.n; k++)
			if (str_eq(segs.v[k], r))
				fail("reserved name '%s' at package '%s' (reserved by shared_descriptor_pool): this name is reserved for "
				     "buffa's generated ancillary types (views, oneof enums, extensions). Rename the proto element.", r, package);
		if (*package)
			continue;
		for (int k = 0; k < pb_count(file, FDP_MESSAGE_TYPE); k++) {
			const char *name = dname(pb_msg_at(file, FDP_MESSAGE_TYPE, k));
			if (str_eq(to_snake_case(name), r))
				fail("reserved name '%s' at message '%s' (its module `%s` is reserved by shared_descriptor_pool): this name "
				     "is reserved for buffa's generated ancillary types (views, oneof enums, extensions). Rename the proto "
				     "element.", r, name, r);
		}
		for (int k = 0; k < pb_count(file, FDP_ENUM_TYPE); k++)
			if (str_eq(dname(pb_msg_at(file, FDP_ENUM_TYPE, k)), r))
				fail("reserved name '%s' at enum '%s' (reserved by shared_descriptor_pool): this name is reserved for buffa's "
				     "generated ancillary types (views, oneof enums, extensions). Rename the proto element.", r, r);
	}
}

static int str_ptr_cmp(const void *a, const void *b) { return strcmp(*(char *const *)a, *(char *const *)b); }

static const char *bc_generate_files(const BcConfig *c, const PbMsg *req, Vec *files)
{
	Vec to_generate = {0};
	int n = pb_count(req, CGR_FILE_TO_GENERATE);
	for (int i = 0; i < n; i++) {
		const char *name = pb_str_at(req, CGR_FILE_TO_GENERATE, i);
		const PbMsg *fd = find_file(req, name);
		if (fd && c->exclude_packages.n && bc_package_is_excluded(pb_str(fd, FDP_PACKAGE), &c->exclude_packages))
			continue;
		vec_push(&to_generate, (void *)name);
	}
	apply_feature_overrides(req, c);
	ctx_init(c, req, &to_generate);

	/* group by package (BTreeMap) */
	Map by_pkg = {0};
	Vec pkgs = {0};
	for (int i = 0; i < to_generate.n; i++) {
		const PbMsg *fd = find_file(req, to_generate.v[i]);
		if (!fd)
			return xcat("file_to_generate '", VEC_AT(to_generate, char, i), "' not found in descriptor set");
		const char *pkg = pb_str(fd, FDP_PACKAGE);
		Vec *v = map_get(&by_pkg, pkg);
		if (!v) {
			v = xalloc(sizeof *v);
			map_put(&by_pkg, pkg, v);
			vec_push(&pkgs, (void *)pkg);
		}
		vec_push(v, (void *)fd);
	}
	if (pkgs.n > 1)
		qsort(pkgs.v, (size_t)pkgs.n, sizeof *pkgs.v, str_ptr_cmp);
	if (c->shared_descriptor_pool)
		validate_shared_root_name(&to_generate);
	Str fds = {"", 0};
	if (c->generate_reflection && !c->shared_descriptor_pool)
		fds = encode_fds_once();
	for (int i = 0; i < pkgs.n; i++)
		generate_package(pkgs.v[i], map_get(&by_pkg, pkgs.v[i]), fds, files);
	return NULL;
}
