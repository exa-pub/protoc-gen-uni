#!/usr/bin/env python3
# Generates wordclass.h: the non-ASCII code points that the re module of CPython 3.11 (Unicode
# 14.0.0) matches with \w (str.isalnum() or "_") and \d (str.isdecimal()), for textwrap.c.
# Dev-only; run with Python 3.11 (its unicodedata is the data):
#
#	python3.11 -I mkwordclass.py > wordclass.h
#
# Each table is a list of ranges after U+007F as varints: the gap since the end of the previous
# range (minus one), then the length of the range minus one.
import re
import sys
import unicodedata

assert sys.version_info[:2] == (3, 11), "run with Python 3.11"
assert unicodedata.unidata_version == "14.0.0"


def ranges(pattern):
    rx = re.compile(pattern)
    out, start = [], None
    for c in range(0x80, 0x110000):
        ok = rx.match(chr(c)) is not None
        if ok and start is None:
            start = c
        if not ok and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def varint(x):
    b = []
    while x >= 0x80:
        b.append(0x80 | (x & 0x7F))
        x >>= 7
    b.append(x)
    return b


def table(name, rs):
    data, prev = [], 0x7F
    for lo, hi in rs:
        data += varint(lo - prev - 1) + varint(hi - lo)
        prev = hi
    print(f"static const uint8_t {name}[] = {{")
    for i in range(0, len(data), 16):
        print("\t" + ", ".join(f"0x{x:02x}" for x in data[i : i + 16]) + ",")
    print("};")


print("/* Code generated by mkwordclass.py with CPython 3.11 (Unicode 14.0.0); DO NOT EDIT.")
print(" *")
print(" * Ranges of non-ASCII code points matched by \\w and \\d of the re module, as varints:")
print(" * gap since the previous range minus one, length minus one. */")
print()
table("py311_word", ranges(r"\w"))
print()
table("py311_digit", ranges(r"\d"))
