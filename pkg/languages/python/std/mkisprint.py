#!/usr/bin/env python3
# Generates isprint.h (the table of str.isprintable() of CPython 3.13) from UnicodeData.txt of
# Unicode 15.1.0 (https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt), the version of
# unicodedata in Python 3.13. Dev-only:
#
#	python3 -I mkisprint.py UnicodeData.txt > isprint.h
#
# A code point is printable unless its category is Cc, Cf, Cs, Co, Cn (unassigned), Zl, Zp or Zs,
# except U+0020 (CPython Tools/unicode/makeunicodedata.py, PRINTABLE_MASK).
import sys

NONPRINT = {"Cc", "Cf", "Cs", "Co", "Zl", "Zp", "Zs"}
PER_LINE = 8


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: mkisprint.py UnicodeData.txt")
    printable = bytearray(0x110000)
    first = None
    with open(sys.argv[1], encoding="ascii") as f:
        for line in f:
            fields = line.split(";")
            cp, name, cat = int(fields[0], 16), fields[1], fields[2]
            ok = cat not in NONPRINT or cp == 0x20
            if name.endswith(", First>"):
                first = cp
                continue
            lo = cp
            if name.endswith(", Last>"):
                lo, first = first, None
            for c in range(lo, cp + 1):
                printable[c] = ok
    ranges = []
    c = 0
    while c < 0x110000:
        if printable[c]:
            lo = c
            while c < 0x110000 and printable[c]:
                c += 1
            ranges.append((lo, c - 1))
        else:
            c += 1
    out = sys.stdout.write
    out("/* Code generated by mkisprint.py from UnicodeData.txt of Unicode 15.1.0; DO NOT EDIT.\n"
        " *\n"
        " * Sorted ranges [lo, hi] of the code points that are printable for CPython 3.13\n"
        " * (str.isprintable). */\n\n")
    bmp = [r for r in ranges if r[1] <= 0xFFFF]
    astral = [r for r in ranges if r[1] > 0xFFFF]
    assert all(r[0] > 0xFFFF for r in astral), "a range crosses U+FFFF"
    for name, typ, rs, width in (("py_print16", "uint16_t", bmp, 4), ("py_print32", "uint32_t", astral, 5)):
        vals = [v for r in rs for v in r]
        out("static const %s %s[] = {\n" % (typ, name))
        for i in range(0, len(vals), PER_LINE):
            out("\t" + " ".join("0x%0*x," % (width, v) for v in vals[i:i + PER_LINE]) + "\n")
        out("};\n")


main()
