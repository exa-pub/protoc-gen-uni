/* Port of Plugins/ConnectPluginUtilities/Generator.swift (connect-swift 1.2.3): the base class
 * of the Connect-Swift generators and its SwiftProtobufPluginLibrary.CodeGenerator conformance. */
#include "connect_plugin_utilities.h"

#include <stdarg.h>
#include <stdlib.h>
#include <string.h>

void cpu_print_content(CpuGenerator *g, SwFile *descriptor)
{
	cpu_print_line(g, "// Code generated by protoc-gen-connect-swift. DO NOT EDIT.");
	cpu_print_line(g, "// swift-format-ignore-file");
	cpu_print_line(g, "// swiftlint:disable all");
	cpu_print_line(g, "//");
	cpu_print_line(g, xcat("// Source: ", descriptor->name));
	cpu_print_line(g, "//");
	cpu_print_line(g, "");
}

void cpu_indent(CpuGenerator *g) { sw_indent(&g->printer); }
void cpu_outdent(CpuGenerator *g) { sw_outdent(&g->printer); }

void cpu_print_line_str(CpuGenerator *g, Str line)
{
	if (line.n)
		sw_print_str(&g->printer, line);
	sw_print(&g->printer, "\n");
}

void cpu_print_line(CpuGenerator *g, const char *line) { cpu_print_line_str(g, str_c(line)); }

void cpu_printf_line(CpuGenerator *g, const char *fmt, ...)
{
	Buf b = {0};
	va_list ap;
	va_start(ap, fmt);
	buf_vfmt(&b, fmt, ap);
	va_end(ap);
	cpu_print_line_str(g, buf_view(&b));
}

void cpu_print_comments_if_needed(CpuGenerator *g, SwKind k, const void *entity)
{
	Str comments = sw_trim_whitespace(sw_proto_source_comments(k, entity, "///", NULL));
	if (comments.n)
		cpu_print_line_str(g, comments);
}

/* Swift's String < for the module names: by Unicode scalars, which is by bytes for ASCII. Other
 * strings compare after normalization (not ported): printModuleImports checks they are ASCII. */
static int compare_modules(const void *a, const void *b)
{
	const Str *x = *(Str *const *)a, *y = *(Str *const *)b;
	size_t n = x->n < y->n ? x->n : y->n;
	int c = memcmp(x->p, y->p, n);
	if (c)
		return c;
	return x->n < y->n ? -1 : x->n > y->n;
}

static Str *new_str(Str s)
{
	Str *p = xalloc(sizeof *p);
	*p = s;
	return p;
}

void cpu_print_module_imports(CpuGenerator *g, const char *const *additional, int n_additional)
{
	Vec all = {0};
	vec_push(&all, new_str(STR_LIT("Connect")));
	vec_push(&all, new_str(STR_LIT("Foundation")));
	vec_push(&all, new_str(g->options->swift_protobuf_module_name));
	for (int i = 0; i < g->needed_modules.n; i++)
		vec_push(&all, new_str(str_c(g->needed_modules.v[i])));
	for (int i = 0; i < g->options->extra_module_imports.n; i++)
		vec_push(&all, g->options->extra_module_imports.v[i]);
	for (int i = 0; i < n_additional; i++)
		vec_push(&all, new_str(str_c(additional[i])));
	for (int i = 0; i < all.n; i++) {
		const Str *s = all.v[i];
		for (size_t j = 0; j < s->n; j++)
			if ((unsigned char)s->p[j] >= 0x80)
				fail("unsupported by protoc-gen-uni: non-ASCII character in module name %s", sw_quote(*s));
	}
	/* sorted() is stable; equal names are equal bytes here. */
	qsort(all.v, (size_t)all.n, sizeof all.v[0], compare_modules);
	for (int i = 0; i < all.n; i++) {
		Buf b = {0};
		buf_adds(&b, "import ");
		buf_add_str(&b, *(Str *)all.v[i]);
		cpu_print_line_str(g, buf_view(&b));
	}
}

/* ---- extension Generator: SwiftProtobufPluginLibrary.CodeGenerator ---- */

/* The generator of the request being served (generateCode passes it as self). */
static CpuGenerator *current;

static Str reset_and_print_file(CpuGenerator *g, SwFile *descriptor)
{
	g->namer = sw_namer(descriptor, g->options->proto_to_module_mappings);
	/* protoToModuleMappings.neededModules(forFile:) ?? []: the mappings never have entries (no
	 * mappings file is read). */
	g->needed_modules = (Vec){0};
	g->services = &descriptor->services;
	sw_printer_init_indent(&g->printer, 4, false);
	g->print_content(g, descriptor);
	return buf_view(&g->printer.content);
}

static void generate(SwFile **files, int n_files, Str parameter, SwOutputs *outputs)
{
	CpuGenerator *g = current;
	g->options = cpu_parse_options(parameter);
	if (!g->options->generate_async_methods && !g->options->generate_callback_methods)
		fail("GeneratorError(message: \"Either async methods or callback methods must be enabled\")");
	for (int i = 0; i < n_files; i++) {
		SwFile *descriptor = files[i];
		if (!descriptor->services.n)
			continue;
		CpuFilePathComponents c = cpu_file_path_components(descriptor->name);
		char *file_name = cpu_output_file_path(&c, g->output_file_extension, g->options->file_naming);
		sw_outputs_add(outputs, file_name, reset_and_print_file(g, descriptor));
	}
}

static const SwCodeGenerator code_generator = {
	.supported_features = 3, /* .proto3Optional, .supportsEditions */
	/* supportedEditionRange: max(bundled minimum, legacy)...min(bundled maximum, 2023) */
	.minimum_edition = SW_EDITION_PROTO2,
	.maximum_edition = SW_EDITION_2023,
	.edition_defaults = &sw_edition_defaults_1_37_0,
	.generate = generate,
};

const char *cpu_main(CpuGenerator *g, PbMsg *req, Buf *out)
{
	/* No customOptionExtensions: the pb.enumvalue.json option is not decoded. */
	const char *err = sw_check_request(req, false);
	if (err)
		return xcat(g->program_name, ": Received an unparsable request from the compiler: ", err);
	current = g;
	sw_generate_code(req, &code_generator, out);
	return NULL;
}
