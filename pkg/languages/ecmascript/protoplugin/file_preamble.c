/* Ported from packages/protoplugin/src/file-preamble.ts. */
#include "internal.h"

#include <string.h>

/* Escapes a value for a `//` comment, like the body of a string literal; also U+2028 and U+2029,
 * because they end a line comment. (The Go port leaves U+2028 and U+2029 unchanged.) v2.13.0
 * escapes nothing. */
static void add_escaped(const Schema *s, Buf *b, Str v)
{
	if (V2_13(s)) {
		buf_add_str(b, v);
		return;
	}
	for (size_t i = 0; i < v.n; i++) {
		const unsigned char *p = (const unsigned char *)v.p + i;
		switch (*p) {
		case '\\': buf_adds(b, "\\\\"); continue;
		case '"': buf_adds(b, "\\\""); continue;
		case '\n': buf_adds(b, "\\n"); continue;
		case '\r': buf_adds(b, "\\r"); continue;
		}
		if (v.n - i >= 3 && p[0] == 0xe2 && p[1] == 0x80 && (p[2] == 0xa8 || p[2] == 0xa9)) {
			buf_adds(b, p[2] == 0xa8 ? "\\u2028" : "\\u2029");
			i += 2;
			continue;
		}
		buf_addc(b, (char)*p);
	}
}

static void write_comment_lines(Buf *b, Str comment)
{
	Str *lines;
	int n = str_split_s(str_trim_suffix_s(comment, STR_LIT("\n")), '\n', &lines);
	for (int j = 0; j < n; j++) {
		buf_adds(b, "//");
		buf_add_str(b, lines[j]);
		buf_addc(b, '\n');
	}
	buf_addc(b, '\n');
}

static void write_leading_comments(Buf *b, Comments c)
{
	for (int i = 0; i < c.n_leading_detached; i++)
		write_comment_lines(b, c.leading_detached[i]);
	if (c.leading.p)
		write_comment_lines(b, c.leading);
}

/* The values of google.protobuf.Edition known to @bufbuild/protobuf v2.17.0 (v2.13.0: without
 * EDITION_2026). */
static const char *edition_name(const Schema *s, int64_t e)
{
	if (e == 1002 && V2_13(s))
		return NULL;
	switch (e) {
	case 0: return "EDITION_UNKNOWN";
	case 900: return "EDITION_LEGACY";
	case 998: return "EDITION_PROTO2";
	case 999: return "EDITION_PROTO3";
	case 1000: return "EDITION_2023";
	case 1001: return "EDITION_2024";
	case 1002: return "EDITION_2026";
	case 9999: return "EDITION_UNSTABLE";
	case 1: return "EDITION_1_TEST_ONLY";
	case 2: return "EDITION_2_TEST_ONLY";
	case 99997: return "EDITION_99997_TEST_ONLY";
	case 99998: return "EDITION_99998_TEST_ONLY";
	case 99999: return "EDITION_99999_TEST_ONLY";
	case 2147483647: return "EDITION_MAX";
	}
	return NULL;
}

/* The edition name without the EDITION_ prefix. */
const char *edition_to_string(const Schema *s, int64_t e)
{
	const char *n = edition_name(s, e);
	return n ? n + strlen("EDITION_") : xfmt("unknown (%lld)", (long long)e);
}

Str make_file_preamble(const Schema *s, DescFile *file)
{
	Buf b = {0};
	write_leading_comments(&b, get_syntax_comments(file));
	buf_adds(&b, "// @generated by ");
	add_escaped(s, &b, str_c(s->plugin_name));
	if (s->plugin_version) {
		buf_addc(&b, ' ');
		add_escaped(s, &b, str_c(s->plugin_version));
	}
	if (s->sanitized_parameter.n) {
		buf_adds(&b, " with parameter \"");
		add_escaped(s, &b, s->sanitized_parameter);
		buf_addc(&b, '"');
	}
	buf_adds(&b, "\n// @generated from file ");
	add_escaped(s, &b, str_c(file->name));
	buf_adds(&b, ".proto (");
	const char *pkg = pb_str(file->h.proto, FDP_PACKAGE);
	if (*pkg) {
		buf_adds(&b, "package ");
		add_escaped(s, &b, str_c(pkg));
		buf_adds(&b, ", ");
	}
	if (file->edition == ED_PROTO2) {
		buf_adds(&b, "syntax proto2)\n");
	} else if (file->edition == ED_PROTO3) {
		buf_adds(&b, "syntax proto3)\n");
	} else {
		/* Report the raw edition from the descriptor so files using EDITION_UNSTABLE (which
		 * we collapse to maximumEdition internally) still render as "edition unstable". */
		const char *n = edition_name(s, pb_int(file->h.proto, FDP_EDITION, 0));
		if (n) {
			char *e = xstrdup(n + strlen("EDITION_"));
			for (char *p = e; *p; p++)
				if (*p >= 'A' && *p <= 'Z')
					*p = (char)(*p - 'A' + 'a');
			buf_adds(&b, xcat("edition ", e, ")\n"));
		} else {
			buf_adds(&b, "unknown edition\n");
		}
	}
	Vec fo = feature_option_strings(&file->h);
	for (int i = 0; i < fo.n; i++)
		buf_adds(&b, xcat("// option ", fo.v[i], ";\n"));
	buf_adds(&b, "/* eslint-disable */\n");
	if (s->opts.ts_nocheck)
		buf_adds(&b, "// @ts-nocheck\n");
	buf_adds(&b, "\n");
	write_leading_comments(&b, get_package_comments(file));
	return str_trim_suffix_s(buf_view(&b), STR_LIT("\n"));
}
