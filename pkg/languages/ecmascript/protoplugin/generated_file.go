// Ported from packages/protoplugin/src/generated-file.ts.

// FileInfo is a generated file.
type FileInfo struct {
	Name     string
	Content  string
	Preamble *string
}

type resolvers struct {
	descImport  func(desc protobuf.Desc, typeOnly bool) *ImportSymbol
	shapeImport func(desc protobuf.Desc) *ImportSymbol
	jsonImport  func(desc protobuf.Desc) *ImportSymbol
	validImport func(desc *protobuf.DescMessage) *ImportSymbol
}

// GeneratedFile is a JavaScript, TypeScript, or TypeScript declaration file.
type GeneratedFile struct {
	name           string
	importPath     string
	jsImportStyle  JSImportStyle
	rewriteImport  func(string) string
	resolve        resolvers
	createPreamble func(*protobuf.DescFile) string
	preamble       *string
	el             []any // string, *ImportSymbol, ExportStatement

	// Runtime provides symbols from the runtime library @bufbuild/protobuf.
	Runtime *RuntimeImports
}

// JSImportStyle reports "legacy_commonjs" with the plugin option js_import_style=legacy_commonjs,
// but only if the current target is "js".
func (f *GeneratedFile) JSImportStyle() JSImportStyle { return f.jsImportStyle }

// Preamble creates a standard preamble that includes comments at the top of the protobuf source
// file (like a license header), as well as information about the code generator and its version.
func (f *GeneratedFile) Preamble(file *protobuf.DescFile) {
	p := f.createPreamble(file)
	f.preamble = &p
}

// Print adds a line of code to the file.
func (f *GeneratedFile) Print(printables ...Printable) {
	f.printableToEl(printables)
	f.el = append(f.el, "\n")
}

// Export creates a printable export statement.
func (f *GeneratedFile) Export(declaration, name string) Printable {
	return ExportStatement{Name: name, Declaration: declaration}
}

// String creates a string literal.
func (f *GeneratedFile) String(s string) Printable {
	return LiteralString{Value: s}
}

// Array creates an array literal.
func (f *GeneratedFile) Array(elements []Printable) Printable {
	p := []Printable{"["}
	for i, e := range elements {
		p = append(p, e)
		if i < len(elements)-1 {
			p = append(p, ", ")
		}
	}
	return append(p, "]")
}

// JSDoc creates a JSDoc comment block with the given text.
func (f *GeneratedFile) JSDoc(text, indentation string) Printable {
	return JSDocBlock{Text: text, Indentation: indentation}
}

// JSDocDesc creates a JSDoc comment block for the given descriptor, with the original comments
// from the protobuf source, and annotations such as `@generated from message MyMessage`.
func (f *GeneratedFile) JSDocDesc(desc protobuf.Desc, indentation string) Printable {
	return JSDocBlock{Text: CreateJSDocTextFromDesc(desc), Indentation: indentation}
}

// ImportSchema imports a descriptor generated by protoc-gen-es.
func (f *GeneratedFile) ImportSchema(desc protobuf.Desc, typeOnly bool) *ImportSymbol {
	return f.resolve.descImport(desc, typeOnly)
}

// ImportShape imports a message or enumeration generated by protoc-gen-es.
func (f *GeneratedFile) ImportShape(desc protobuf.Desc) *ImportSymbol {
	return f.resolve.shapeImport(desc)
}

// ImportJSON imports a message or enumeration JSON type generated by protoc-gen-es.
func (f *GeneratedFile) ImportJSON(desc protobuf.Desc) *ImportSymbol {
	return f.resolve.jsonImport(desc)
}

// ImportValid imports a message Valid type generated by protoc-gen-es.
func (f *GeneratedFile) ImportValid(desc *protobuf.DescMessage) *ImportSymbol {
	return f.resolve.validImport(desc)
}

// Import imports any symbol from a file or package.
func (f *GeneratedFile) Import(name, from string, typeOnly bool) *ImportSymbol {
	return NewImportSymbol(name, from, typeOnly)
}

// FileInfo returns the generated file.
func (f *GeneratedFile) FileInfo() FileInfo {
	return FileInfo{
		Name:     f.name,
		Content:  elToContent(f.el, f.importPath, f.rewriteImport, f.jsImportStyle == JSImportStyleLegacyCommonJS),
		Preamble: f.preamble,
	}
}

func (f *GeneratedFile) printableToEl(printables []Printable) {
	for _, p := range printables {
		switch p := p.(type) {
		case []Printable:
			f.printableToEl(p)
		case string:
			f.el = append(f.el, p)
		case int:
			f.el = append(f.el, strconv.Itoa(p))
		case int32:
			f.el = append(f.el, strconv.FormatInt(int64(p), 10))
		case int64:
			f.el = append(f.el, strconv.FormatInt(p, 10))
		case uint32:
			f.el = append(f.el, strconv.FormatUint(uint64(p), 10))
		case uint64:
			f.el = append(f.el, strconv.FormatUint(p, 10))
		case float64:
			f.el = append(f.el, formatNumber(p))
		case bool:
			f.el = append(f.el, strconv.FormatBool(p))
		case []byte:
			if len(p) == 0 {
				f.el = append(f.el, "new Uint8Array(0)")
				break
			}
			strs := make([]string, len(p))
			for i, n := range p {
				strs[i] = fmt.Sprintf("0x%02X", n)
			}
			f.el = append(f.el, "new Uint8Array(["+strings.Join(strs, ", ")+"])")
		case *ImportSymbol:
			f.el = append(f.el, p)
		case ExportStatement:
			f.el = append(f.el, p)
		case DescImport:
			f.el = append(f.el, f.resolve.descImport(p.Desc, p.TypeOnly))
		case ShapeImport:
			f.el = append(f.el, f.resolve.shapeImport(p.Desc))
		case JSONTypeImport:
			f.el = append(f.el, f.resolve.jsonImport(p.Desc))
		case ValidTypeImport:
			f.el = append(f.el, f.resolve.validImport(p.Desc))
		case JSDocBlock:
			f.el = append(f.el, FormatJSDocBlock(p.Text, p.Indentation))
		case LiteralString:
			f.el = append(f.el, escapeString(p.Value))
		case LiteralProtoInt64:
			switch {
			case p.LongAsString:
				f.el = append(f.el, escapeString(p.Value))
			case isZero(p.Value):
				f.el = append(f.el, f.Runtime.ProtoInt64, ".zero")
			case p.Type == protobuf.ScalarUint64 || p.Type == protobuf.ScalarFixed64:
				f.el = append(f.el, f.Runtime.ProtoInt64, ".uParse(", escapeString(p.Value), ")")
			default:
				f.el = append(f.el, f.Runtime.ProtoInt64, ".parse(", escapeString(p.Value), ")")
			}
		default:
			panic(fmt.Errorf("cannot print %T", p))
		}
	}
}

func isZero(decimal string) bool {
	return strings.Trim(strings.TrimPrefix(decimal, "-"), "0") == ""
}

// formatNumber formats a number like Number.prototype.toString(10).
func formatNumber(f float64) string {
	switch {
	case math.IsNaN(f):
		return "globalThis.NaN"
	case math.IsInf(f, 1):
		return "globalThis.Infinity"
	case math.IsInf(f, -1):
		return "-globalThis.Infinity"
	case f == 0:
		return "0"
	}
	abs := math.Abs(f)
	if abs >= 1e21 || abs < 1e-6 {
		s := strconv.FormatFloat(f, 'e', -1, 64)
		mant, exp, _ := strings.Cut(s, "e")
		if exp[0] == '+' {
			return mant + "e+" + strings.TrimLeft(exp[1:], "0")
		}
		return mant + "e-" + strings.TrimLeft(exp[1:], "0")
	}
	return strconv.FormatFloat(f, 'f', -1, 64)
}

func elToContent(el []any, importerPath string, rewriteImportPath func(string) string, legacyCommonJS bool) string {
	if len(el) == 0 {
		return ""
	}
	var c strings.Builder
	if legacyCommonJS {
		c.WriteString("\"use strict\";\n")
		c.WriteString("Object.defineProperty(exports, \"__esModule\", { value: true });\n")
		c.WriteString("\n")
	}
	wroteImports := legacyCommonJS
	symbolToIdentifier := processImports(el, importerPath, rewriteImportPath, func(typeOnly bool, from string, names []importName) {
		wroteImports = true
		if legacyCommonJS {
			p := make([]string, len(names))
			for i, n := range names {
				if n.alias == "" {
					p[i] = n.name
				} else {
					p[i] = n.name + ": " + n.alias
				}
			}
			c.WriteString("const { " + strings.Join(p, ", ") + " } = require(" + escapeString(from) + ");\n")
			return
		}
		p := make([]string, len(names))
		for i, n := range names {
			if n.alias == "" {
				p[i] = n.name
			} else {
				p[i] = n.name + " as " + n.alias
			}
		}
		what := "{ " + strings.Join(p, ", ") + " }"
		if typeOnly {
			c.WriteString("import type " + what + " from " + escapeString(from) + ";\n")
		} else {
			c.WriteString("import " + what + " from " + escapeString(from) + ";\n")
		}
	})
	if wroteImports {
		c.WriteString("\n")
	}
	var legacyCommonJSExportNames []string
	for _, e := range el {
		switch e := e.(type) {
		case string:
			c.WriteString(e)
		case *ImportSymbol:
			if ident, ok := symbolToIdentifier[e.ID()]; ok {
				c.WriteString(ident)
			}
		case ExportStatement:
			if legacyCommonJS {
				legacyCommonJSExportNames = append(legacyCommonJSExportNames, e.Name)
			} else {
				c.WriteString("export ")
			}
			if e.Declaration != "" {
				c.WriteString(e.Declaration + " ")
			}
			c.WriteString(e.Name)
		}
	}
	if legacyCommonJS {
		if len(legacyCommonJSExportNames) > 0 {
			c.WriteString("\n")
		}
		for _, name := range legacyCommonJSExportNames {
			c.WriteString("exports." + name + " = " + name + ";\n")
		}
	}
	return c.String()
}

type importName struct {
	name, alias string
}

// orderedMap is a map that keeps the insertion order of keys, like a JavaScript Map.
type orderedMap struct {
	keys   []string
	values map[string]string
}

func (m *orderedMap) set(k, v string) {
	if m.values == nil {
		m.values = map[string]string{}
	}
	if _, ok := m.values[k]; !ok {
		m.keys = append(m.keys, k)
	}
	m.values[k] = v
}

func processImports(el []any, importerPath string, rewriteImportPath func(string) string, makeImportStatement func(typeOnly bool, from string, names []importName)) map[string]string {
	// identifiers to use in the output
	symbolToIdentifier := map[string]string{}
	// symbols that need a value import (as opposed to a type-only import)
	symbolToIsValue := map[string]bool{}
	// taken in this file
	identifiersTaken := map[string]bool{}
	// foreign symbols need an import
	var foreignSymbols []*ImportSymbol

	// Walk through all symbols used and populate the collections above.
	for _, s := range el {
		switch s := s.(type) {
		case *ImportSymbol:
			symbolToIdentifier[s.ID()] = s.Name
			if !s.TypeOnly {
				// a symbol is only type-imported as long as all uses are type-only
				symbolToIsValue[s.ID()] = true
			}
			if s.From == importerPath {
				identifiersTaken[s.Name] = true
			} else {
				foreignSymbols = append(foreignSymbols, s)
			}
		case ExportStatement:
			identifiersTaken[s.Name] = true
		}
	}

	// Walk through all foreign symbols and make their identifiers unique.
	handledSymbols := map[string]bool{}
	for _, s := range foreignSymbols {
		if handledSymbols[s.ID()] {
			continue
		}
		handledSymbols[s.ID()] = true
		if !identifiersTaken[s.Name] {
			identifiersTaken[s.Name] = true
			continue
		}
		var alias string
		for i := 1; ; i++ {
			// We choose '$' because it is invalid in proto identifiers.
			alias = s.Name + "$" + strconv.Itoa(i)
			if !identifiersTaken[alias] {
				break
			}
		}
		identifiersTaken[alias] = true
		symbolToIdentifier[s.ID()] = alias
	}

	// Group foreign symbols (imports) by their source (from).
	type imp struct {
		types  orderedMap
		values orderedMap
	}
	sourceToImport := map[string]*imp{}
	for _, s := range foreignSymbols {
		i := sourceToImport[s.From]
		if i == nil {
			i = &imp{}
			sourceToImport[s.From] = i
		}
		alias := symbolToIdentifier[s.ID()]
		if alias == s.Name {
			alias = ""
		}
		if symbolToIsValue[s.ID()] {
			i.values.set(s.Name, alias)
		} else {
			i.types.set(s.Name, alias)
		}
	}

	// Make import statements.
	handledSource := map[string]bool{}
	buildNames := func(m *orderedMap) []importName {
		names := make([]importName, 0, len(m.keys))
		for _, k := range m.keys {
			names = append(names, importName{k, m.values[k]})
		}
		slices.SortStableFunc(names, func(a, b importName) int { return LocaleCompare(a.name, b.name) })
		return names
	}
	for _, s := range foreignSymbols {
		if handledSource[s.From] {
			continue
		}
		handledSource[s.From] = true
		i := sourceToImport[s.From]
		from := MakeImportPathRelative(importerPath, rewriteImportPath(s.From))
		if len(i.types.keys) > 0 {
			makeImportStatement(true, from, buildNames(&i.types))
		}
		if len(i.values.keys) > 0 {
			makeImportStatement(false, from, buildNames(&i.values))
		}
	}
	return symbolToIdentifier
}

func escapeString(value string) string {
	return `"` + stringEscaper.Replace(value) + `"`
}

var stringEscaper = strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\r", `\r`, "\n", `\n`)

func itoa(i int64) string { return strconv.FormatInt(i, 10) }
