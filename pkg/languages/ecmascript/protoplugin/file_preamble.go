package protoplugin

import (
	"strings"

	"google.golang.org/protobuf/types/descriptorpb"

	"github.com/exa-pub/protoc-gen-uni/pkg/languages/ecmascript/protobuf"
)

// Ported from packages/protoplugin/src/file-preamble.ts.

func makeFilePreamble(file *protobuf.DescFile, pluginName string, pluginVersion *string, parameter string, tsNoCheck bool) string {
	var b strings.Builder
	writeLeadingComments := func(comments DescComments) {
		for _, comment := range comments.LeadingDetached {
			comment = strings.TrimSuffix(comment, "\n")
			for _, line := range strings.Split(comment, "\n") {
				b.WriteString("//" + line + "\n")
			}
			b.WriteString("\n")
		}
		if comments.Leading != nil {
			comment := strings.TrimSuffix(*comments.Leading, "\n")
			for _, line := range strings.Split(comment, "\n") {
				b.WriteString("//" + line + "\n")
			}
			b.WriteString("\n")
		}
	}
	writeLeadingComments(GetSyntaxComments(file))
	if pluginVersion == nil {
		b.WriteString("// @generated by " + escapeValue(pluginName))
	} else {
		b.WriteString("// @generated by " + escapeValue(pluginName) + " " + escapeValue(*pluginVersion))
	}
	if parameter != "" {
		b.WriteString(` with parameter "` + escapeValue(parameter) + `"`)
	}
	b.WriteString("\n")
	b.WriteString("// @generated from file " + escapeValue(file.Name) + ".proto (")
	if file.Proto.GetPackage() != "" {
		b.WriteString("package " + escapeValue(file.Proto.GetPackage()) + ", ")
	}
	switch file.Edition {
	case protobuf.EditionProto2:
		b.WriteString("syntax proto2)\n")
	case protobuf.EditionProto3:
		b.WriteString("syntax proto3)\n")
	default:
		// Report the raw edition from the descriptor so files using
		// EDITION_UNSTABLE (which we collapse to maximumEdition internally)
		// still render as "edition unstable".
		if name, ok := editionNames[file.Proto.GetEdition()]; ok {
			e := strings.ToLower(strings.Replace(name, "EDITION_", "", 1))
			b.WriteString("edition " + e + ")\n")
		} else {
			b.WriteString("unknown edition\n")
		}
	}
	for _, o := range GetFeatureOptionStrings(file) {
		b.WriteString("// option " + o + ";\n")
	}
	b.WriteString("/* eslint-disable */\n")
	if tsNoCheck {
		b.WriteString("// @ts-nocheck\n")
	}
	b.WriteString("\n")
	writeLeadingComments(GetPackageComments(file))
	return strings.TrimSuffix(b.String(), "\n")
}

// editionNames are the values of google.protobuf.Edition known to @bufbuild/protobuf v2.17.0.
var editionNames = map[descriptorpb.Edition]string{
	0:          "EDITION_UNKNOWN",
	900:        "EDITION_LEGACY",
	998:        "EDITION_PROTO2",
	999:        "EDITION_PROTO3",
	1000:       "EDITION_2023",
	1001:       "EDITION_2024",
	1002:       "EDITION_2026",
	9999:       "EDITION_UNSTABLE",
	1:          "EDITION_1_TEST_ONLY",
	2:          "EDITION_2_TEST_ONLY",
	99997:      "EDITION_99997_TEST_ONLY",
	99998:      "EDITION_99998_TEST_ONLY",
	99999:      "EDITION_99999_TEST_ONLY",
	2147483647: "EDITION_MAX",
}

// editionToString returns the edition name without the EDITION_ prefix.
func editionToString(edition descriptorpb.Edition) string {
	if name, ok := editionNames[edition]; ok {
		return strings.TrimPrefix(name, "EDITION_")
	}
	return "unknown (" + itoa(int64(edition)) + ")"
}

// escapeValue escapes a value for a `//` comment, like the body of a string literal. Also escapes
// U+2028 and U+2029, because they end a line comment.
func escapeValue(value string) string {
	return valueEscaper.Replace(value)
}

var valueEscaper = strings.NewReplacer(
	`\`, `\\`,
	`"`, `\"`,
	"\n", `\n`,
	"\r", `\r`,
	" ", ` `,
	" ", ` `,
)
