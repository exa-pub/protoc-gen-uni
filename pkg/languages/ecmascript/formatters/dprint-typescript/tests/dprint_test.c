/* Unit tests of the dprint-plugin-typescript 0.87.1 port: dprint-core writer/printer behaviour
 * (cases from dprint-core 0.62.1 src/formatting/writer.rs tests) and node fixtures: trees built
 * with the node API for ts-poet texts that ts-proto 2.18.1 produced, with the output of
 * dprint-node 1.0.8 (ts-poet 6.12.0's options) for that text. */
#include "test.h"

#include "dprint_typescript.c"

static void test_writer(void)
{
	/* write_indented_writes, markexpectnewline_writesnewline */
	Items items = {0};
	items_push_str(&items, "1");
	items_push_signal(&items, SIG_NEW_LINE);
	items_push_signal(&items, SIG_START_INDENT);
	items_push_str(&items, "2");
	items_push_signal(&items, SIG_FINISH_INDENT);
	items_push_signal(&items, SIG_NEW_LINE);
	items_push_str(&items, "3");
	items_push_signal(&items, SIG_EXPECT_NEW_LINE);
	items_push_str(&items, "4");
	Buf out = {0};
	dprint_print(items, (PrintOptions){40, 2, false, "\n"}, &out);
	CHECK_STR(buf_str(&out), "1\n  2\n3\n4");
}

static void test_possible_new_line(void)
{
	/* SpaceOrNewLine breaks when the text would exceed the width */
	Items items = {0};
	items_push_str(&items, "aaaaa");
	items_push_signal(&items, SIG_SPACE_OR_NEW_LINE);
	items_push_str(&items, "bbbbb");
	items_push_signal(&items, SIG_SPACE_OR_NEW_LINE);
	items_push_str(&items, "ccccc");
	Buf out = {0};
	dprint_print(items, (PrintOptions){12, 2, false, "\n"}, &out);
	CHECK_STR(buf_str(&out), "aaaaa bbbbb\nccccc");
}

static void check_module(Node *m, const char *want)
{
	Buf out = {0};
	dprint_ts_format_module(m, &out);
	CHECK_STR(buf_str(&out), want);
}

static NodeList list1(Node *a)
{
	NodeList l = {0};
	dts_add(&l, a);
	return l;
}

/* function isSet(value: any): boolean {\nreturn value !== null && value !== undefined;\n} */
static void test_function(void)
{
	Node *m = dts_module();
	Node *body = dts_block();
	dts_block_add(body, dts_return(dts_bin(TK_LOGICAL_AND, dts_bin(TK_NOTEQEQ, dts_id("value"), dts_null()),
					     dts_bin(TK_NOTEQEQ, dts_id("value"), dts_id("undefined")))));
	Node *f = dts_function(list1(dts_param(dts_binding("value", dts_tkw("any"), false), NULL)), NULL,
			       dts_tkw("boolean"), body, 0);
	dts_block_add(m, dts_fn_decl(dts_id("isSet"), f));
	check_module(m, "function isSet(value: any): boolean {\n  return value !== null && value !== undefined;\n}\n");
}

/* ts-poet text of an interface (ts-proto 2.18.1, google/protobuf/descriptor.proto):
 *   export interface FileDescriptorProto {
 *   (JSDoc: file name, relative to root of source tree)
 *   name?: string | undefined,
 *   (JSDoc: e.g. "foo", "foo.bar", etc.)
 *   package?: string | undefined,
 *   dependency: string[],
 *   }
 * A union followed by `,` and a comment on the next line is broken (dprint's
 * has_any_node_comment_on_different_line looks past the comma); the last one is not. */
static void test_interface_comma_comment(void)
{
	Node *m = dts_module();
	Node *i = dts_interface(dts_id("FileDescriptorProto"), NULL);
	Node *a = dts_prop_sig(dts_id("name"), dts_tunion(dts_tkw("string"), dts_tkw("undefined"), NULL), true, false);
	dts_comment(a, STR_LIT("/** file name, relative to root of source tree */"), true, 0);
	Node *b = dts_prop_sig(dts_id("package"), dts_tunion(dts_tkw("string"), dts_tkw("undefined"), NULL), true, false);
	dts_comment(b, STR_LIT("/** e.g. \"foo\", \"foo.bar\", etc. */"), true, 0);
	Node *c = dts_prop_sig(dts_id("dependency"), dts_tarray(dts_tkw("string")), false, false);
	dts_interface_add(i, dts_hint(a, H_SEP_COMMA));
	dts_interface_add(i, dts_hint(b, H_SEP_COMMA));
	dts_interface_add(i, dts_hint(c, H_SEP_COMMA));
	dts_block_add(m, dts_export(i));
	check_module(m, "export interface FileDescriptorProto {\n"
			"  /** file name, relative to root of source tree */\n"
			"  name?:\n"
			"    | string\n"
			"    | undefined;\n"
			"  /** e.g. \"foo\", \"foo.bar\", etc. */\n"
			"  package?: string | undefined;\n"
			"  dependency: string[];\n"
			"}\n");
}

/* `export interface Empty {\n}` keeps its line break; imports are sorted case-sensitively;
 * blank lines and leading comments are kept. */
static void test_module_layout(void)
{
	Node *m = dts_module();
	Node *i1 = dts_import(dts_str(STR_LIT("\"./x\"")), false);
	dts_import_named(i1, NULL, dts_id("b"), false);
	dts_import_named(i1, NULL, dts_id("a"), false);
	Node *i2 = dts_import(dts_str(STR_LIT("\"@y/z\"")), false);
	dts_import_named(i2, NULL, dts_id("c"), false);
	dts_comment(i1, STR_LIT("// Code generated by protoc-gen-ts_proto. DO NOT EDIT."), false, 0);
	dts_comment(i1, STR_LIT("/* eslint-disable */"), true, NL_BLANK);
	dts_block_add(m, i1);
	dts_block_add(m, i2);
	Node *e = dts_interface(dts_id("Empty"), NULL);
	e->c->hints |= H_CLOSE_NL;
	dts_block_add(m, dts_nl(dts_export(e), NL_BLANK));
	check_module(m, "// Code generated by protoc-gen-ts_proto. DO NOT EDIT.\n\n/* eslint-disable */\n"
			"import { c } from \"@y/z\";\nimport { a, b } from \"./x\";\n\nexport interface Empty {\n}\n");
}

/* A conditional broken in the source and too long for one line (ts-proto fromJSON of repeated
 * fields):
 *   return {
 *   uninterpretedOption: globalThis.Array.isArray(object?.uninterpretedOption)
 *   ? object.uninterpretedOption.map((e: any) => UninterpretedOption.fromJSON(e))
 *   : [],
 *   }; */
static void test_conditional(void)
{
	Node *m = dts_module();
	Node *obj = dts_obj();
	Node *isarr = dts_call(dts_member(dts_member(dts_id("globalThis"), "Array"), "isArray"),
			       dts_opt_member(dts_id("object"), "uninterpretedOption", true), NULL);
	NodeList ps = list1(dts_binding("e", dts_tkw("any"), false));
	Node *arrow = dts_arrow(ps, NULL, dts_call(dts_member(dts_id("UninterpretedOption"), "fromJSON"), dts_id("e"), NULL), 0);
	Node *map = dts_call(dts_member(dts_member(dts_id("object"), "uninterpretedOption"), "map"), arrow, NULL);
	Node *cond = dts_hint(dts_cond(isarr, map, dts_arr(NULL)), H_OP_NL | H_OP2_NL);
	dts_obj_add(obj, dts_nl(dts_kvc("uninterpretedOption", cond), NL_LINE));
	obj->hints |= H_TRAILING_COMMA | H_CLOSE_NL;
	Node *body = dts_block();
	dts_block_add(body, dts_return(obj));
	Node *f = dts_function((NodeList){0}, NULL, NULL, body, 0);
	dts_block_add(m, dts_fn_decl(dts_id("f"), f));
	check_module(m, "function f() {\n"
			"  return {\n"
			"    uninterpretedOption: globalThis.Array.isArray(object?.uninterpretedOption)\n"
			"      ? object.uninterpretedOption.map((e: any) => UninterpretedOption.fromJSON(e))\n"
			"      : [],\n"
			"  };\n"
			"}\n");
}

/* Width: a call that does not fit in 120 columns breaks its arguments. */
static void test_width(void)
{
	Node *m = dts_module();
	Node *args[3];
	for (int k = 0; k < 3; k++)
		args[k] = dts_str(str_c(xfmt("\"%s_%d\"", "a_rather_long_string_argument_to_exceed_the_width", k)));
	dts_block_add(m, dts_expr_stmt(dts_call(dts_id("f"), args[0], args[1], args[2], NULL)));
	check_module(m, "f(\n"
			"  \"a_rather_long_string_argument_to_exceed_the_width_0\",\n"
			"  \"a_rather_long_string_argument_to_exceed_the_width_1\",\n"
			"  \"a_rather_long_string_argument_to_exceed_the_width_2\",\n"
			");\n");
}

/* dprint-node: `export interface class { new(a: string): X; }` parses (an interface name may be a
 * keyword) and prints `new (a: string): X;`, a construct signature; `const class = 1` does not
 * parse (ts-poet then keeps the unformatted text). */
static void test_reserved_names(void)
{
	Node *m = dts_module();
	Node *i = dts_interface(dts_id("class"), NULL);
	dts_interface_add(i, dts_method_sig(dts_id("new"), NULL, list1(dts_binding("a", dts_tkw("string"), false)),
					    dts_tref_node(dts_entity("X"), (NodeList){0}), false));
	dts_block_add(m, dts_export(i));
	CHECK(dprint_ts_reserved_name(m) == NULL);
	check_module(m, "export interface class {\n  new (a: string): X;\n}\n");
	Node *m2 = dts_module();
	dts_block_add(m2, dts_var(VAR_CONST, dts_binding("class", NULL, false), dts_num("1")));
	CHECK_STR(dprint_ts_reserved_name(m2), "class");
}

/* one statement in a module: the reserved name swc rejects in it */
static const char *reserved_in(Node *stmt)
{
	Node *m = dts_module();
	dts_block_add(m, stmt);
	return dprint_ts_reserved_name(m);
}

/* `export function f(): <ret> { return <e>; }` */
static Node *fn_returning(Node *ret, Node *e)
{
	Node *body = dts_block();
	dts_block_add(body, dts_return(e));
	return dts_export(dts_fn_decl(dts_id("f"), dts_function((NodeList){0}, NULL, ret, body, 0)));
}

/* positions checked against dprint-node 1.0.8 (swc_ecma_parser 0.139.0) in a module */
static void test_reserved_positions(void)
{
	/* `export const interface: M<interface> = 1;` parses, `interface.x` does not */
	CHECK(reserved_in(dts_export(dts_var(VAR_CONST, dts_binding("interface", dts_tref("M", dts_tref("interface", NULL), NULL), false),
					   dts_num("1")))) == NULL);
	CHECK_STR(reserved_in(fn_returning(NULL, dts_member(dts_id("interface"), "x"))), "interface");
	CHECK_STR(reserved_in(dts_export(dts_var(VAR_CONST, dts_binding("enum", NULL, false), dts_num("1")))), "enum");
	/* `let.x` parses, a type `let` does not */
	CHECK(reserved_in(fn_returning(NULL, dts_member(dts_id("let"), "x"))) == NULL);
	CHECK_STR(reserved_in(fn_returning(dts_tref("let", NULL), dts_num("1"))), "let");
	/* `(): public {` takes `public` for a modifier; `(): Promise<public> {` and `public[]` */
	CHECK_STR(reserved_in(fn_returning(dts_tref("public", NULL), dts_num("1"))), "public");
	CHECK(reserved_in(fn_returning(dts_tref("Promise", dts_tref("public", NULL), NULL), dts_num("1"))) == NULL);
	CHECK_STR(reserved_in(fn_returning(dts_tarray(dts_tref("public", NULL)), dts_num("1"))), "public");
	/* `keyof[]` is `keyof []`; a type `keyof` alone is not */
	CHECK(reserved_in(fn_returning(dts_tarray(dts_tref("keyof", NULL)), dts_num("1"))) == NULL);
	CHECK_STR(reserved_in(fn_returning(dts_tref("keyof", NULL), dts_num("1"))), "keyof");
	/* `static`, `this` and `super.x` */
	CHECK(reserved_in(fn_returning(dts_tref("static", NULL), dts_member(dts_id("static"), "x"))) == NULL);
	CHECK(reserved_in(fn_returning(dts_tref("this", NULL), dts_member(dts_id("super"), "x"))) == NULL);
	CHECK_STR(reserved_in(fn_returning(NULL, dts_id("super"))), "super");
	/* `class C implements implements {` parses as a class without implements;
	 * `implements implements<X>` does not parse */
	for (int targs = 0; targs < 2; targs++) {
		Node *m = dts_module();
		Node *cls = dts_class(NULL, NULL);
		Node *impl = dts_new(N_TS_EXPR_WITH_TYPE_ARGS);
		impl->a = dts_id("implements");
		if (targs)
			impl->b = dts_targs(list1(dts_tref("X", NULL)));
		dts_add(&cls->list3, impl);
		dts_block_add(m, dts_export(dts_class_decl(dts_id("C"), cls)));
		if (targs) {
			CHECK_STR(dprint_ts_reserved_name(m), "implements");
		} else {
			CHECK(dprint_ts_reserved_name(m) == NULL);
			check_module(m, "export class C {}\n");
		}
	}
}

