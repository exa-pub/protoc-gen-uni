#!/usr/bin/env bash
# Generates pkg/core/isprint.h, the tables of Go's strconv.IsPrint used by quote_go(), from
# $GOROOT/src/strconv/isprint.go of the installed Go toolchain (dev-only; the output is committed).
#
#   scripts/gen-isprint.sh [GOROOT]
#
# isPrint32 is split into the entries below 0x20000 (stored as uint16 offsets from 0x10000) and
# the few above it (uint32), which saves about 1 KB. isGraphic is not needed by strconv.Quote.
set -euo pipefail
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
goroot=${1:-$(go env GOROOT)}
src=$goroot/src/strconv/isprint.go
version=$(head -1 "$goroot/VERSION" 2>/dev/null || go version | awk '{print $3}')
out=$root/pkg/core/isprint.h

table() { awk -v name="$1" '$0 ~ "^var " name " = " { on = 1; next } on && /^}/ { exit } on' "$src" | grep -o '0x[0-9a-f]*'; }

emit() { # name ctype values...
	local name=$1 type=$2
	shift 2
	printf 'static const %s %s[] = {' "$type" "$name"
	local i=0
	for v in "$@"; do
		if [ $((i % 8)) = 0 ]; then printf '\n\t'; else printf ' '; fi
		printf '0x%04x,' "$v"
		i=$((i + 1))
	done
	printf '\n};\n'
}

mapfile -t p16 < <(table isPrint16)
mapfile -t np16 < <(table isNotPrint16)
mapfile -t p32 < <(table isPrint32)
mapfile -t np32 < <(table isNotPrint32)
lo=() hi=()
for v in "${p32[@]}"; do
	if [ $((v)) -lt $((0x20000)) ]; then lo+=($((v - 0x10000))); else hi+=($((v))); fi
done
[ $((${#lo[@]} % 2)) = 0 ] || { echo "a range of isPrint32 spans 0x20000" >&2; exit 1; }

{
	echo "/* Code generated by scripts/gen-isprint.sh from src/strconv/isprint.go of $version. DO NOT EDIT."
	echo " *"
	echo " * Copyright 2013 The Go Authors. All rights reserved. Use of this source code is governed by"
	echo " * a BSD-style license that can be found in the LICENSE file of the Go distribution."
	echo " *"
	echo " * Sorted range pairs [lo, hi] of printable runes, and exceptions inside the ranges. */"
	echo
	emit isPrint16 uint16_t "${p16[@]}"
	echo
	emit isNotPrint16 uint16_t "${np16[@]}"
	echo
	echo "/* isPrint32 entries below 0x20000, minus 0x10000 */"
	emit isPrint32lo uint16_t "${lo[@]}"
	echo
	echo "/* isPrint32 entries from 0x20000 */"
	emit isPrint32hi uint32_t "${hi[@]}"
	echo
	echo "/* minus 0x10000 */"
	emit isNotPrint32 uint16_t "${np32[@]}"
} >"$out"
echo "wrote $out"
