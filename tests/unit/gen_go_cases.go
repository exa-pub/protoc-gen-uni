// Prints the expected values of the unit tests of pkg/core (tests/unit/core_test.c) that come from
// the Go standard library: strconv.Quote, strings.TrimSpace and utf8.DecodeRuneInString.
//
//	go run tests/unit/gen_go_cases.go > tests/unit/go_cases.h
package main

import (
	"fmt"
	"runtime"
	"strconv"
	"strings"
	"unicode/utf8"
)

// cstr renders s as a C string literal with explicit length (hex escapes for non-ASCII).
func cstr(s string) string {
	var b strings.Builder
	b.WriteString(`"`)
	hex := false
	for i := 0; i < len(s); i++ {
		c := s[i]
		isHex := strings.IndexByte("0123456789abcdefABCDEF", c) >= 0
		if hex && isHex {
			b.WriteString(`""`)
		}
		hex = false
		switch {
		case c == '"' || c == '\\':
			b.WriteString(`\` + string(c))
		case c >= 0x20 && c < 0x7f && c != '?':
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, `\x%02x`, c)
			hex = true
		}
	}
	b.WriteString(`"`)
	return b.String()
}

