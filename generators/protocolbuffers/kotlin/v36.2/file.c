/* Port of src/google/protobuf/compiler/kotlin/file.{h,cc}: FileGenerator. */

typedef struct {
	const LpFile *file;
	char *java_package;
	KtMessageGen *message_generators;
	JvContext *context;
	JvOptions options;
} KtFileGenerator;

static KtFileGenerator *kt_file_generator_new(const LpFile *file, const JvOptions *options)
{
	KtFileGenerator *g = xalloc(sizeof *g);
	g->file = file;
	g->java_package = jv_file_java_package(file);
	g->context = jv_context_new(file, options);
	g->options = *options;
	g->message_generators = xalloc(sizeof(KtMessageGen) * ((size_t)file->n_messages + 1));
	for (int i = 0; i < file->n_messages; i++)
		kt_message_generator_init(&g->message_generators[i], &file->messages[i], g->context);
	return g;
}

static char *kt_file_generator_get_kotlin_classname(const KtFileGenerator *g)
{
	return xcat(jv_get_file_immutable_class_name(g->file), "Kt");
}

/* The header of FileGenerator::Generate and of every sibling */
static void kt_print_file_header(const KtFileGenerator *g, LpPrinter *p, const char *filename)
{
	lp_print(p,
		 "// Generated by the protocol buffer compiler. DO NOT EDIT!\n"
		 "// NO CHECKED-IN PROTOBUF "
		 /* Intentional line breaker */
		 "GENCODE\n"
		 "// source: $filename$\n"
		 "\n",
		 "filename", filename, NULL);
	lp_print(p,
		 "@file:com.google.protobuf.Generated\n"
		 "// Generated files should ignore deprecation warnings\n"
		 "@file:Suppress(\"DEPRECATION\")\n",
		 NULL);
	if (*g->java_package) {
		lp_print(p,
			 "package $package$;\n"
			 "\n",
			 "package", jv_escape_kotlin_keywords(g->java_package), NULL);
	}
}

static void kt_file_generator_generate(const KtFileGenerator *g, LpPrinter *p)
{
	kt_print_file_header(g, p, g->file->name);
}

/* printer.Emit({{"annotations_base64", ...}}, "// google.protobuf.GeneratedCodeInfo: ...") */
static void kt_print_annotations(LpPrinter *p, Buf *annotations)
{
	LpSub subs[] = {LP_SUB("annotations_base64", lp_base64_escape(buf_view(annotations)))};
	lp_emit(p, subs, 1, "// google.protobuf.GeneratedCodeInfo: $annotations_base64$\n");
}

static void kt_file_generator_generate_siblings(const KtFileGenerator *g, const char *package_dir, LpContext *context,
						Vec *file_list)
{
	for (int i = 0; i < g->file->n_messages; i++) {
		const LpMessage *descriptor = &g->file->messages[i];
		const KtMessageGen *generator = &g->message_generators[i];
		char *filename = xcat(package_dir, descriptor->name, "Kt.kt");
		vec_push(file_list, filename);
		Buf annotations = {0};
		LpPrinter printer;
		lp_printer_init(&printer, lp_context_open(context, filename), '$');
		if (g->options.annotate_code)
			printer.annotations = &annotations;

		kt_print_file_header(g, &printer, descriptor->file->name);

		kt_message_generator_generate_members(generator, &printer);
		kt_message_generator_generate_top_level_members(generator, &printer);

		if (g->options.annotate_code)
			kt_print_annotations(&printer, &annotations);
	}
}
