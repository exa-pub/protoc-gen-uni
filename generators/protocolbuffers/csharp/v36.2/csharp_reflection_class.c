/* Port of src/google/protobuf/compiler/csharp/csharp_reflection_class.{h,cc} (protobuf v36.2):
 * ReflectionClassGenerator. */

typedef struct {
	const LpFile *file;
	const CsOptions *options;
	const char *namespace_;
	const char *reflection_classname;
	const char *extension_classname;
	bool nrt_enabled;
} CsReflectionClassGen;

static void cs_reflection_write_introduction(CsReflectionClassGen *r, LpPrinter *printer)
{
	lp_print(printer,
		 "// <auto-generated>\n"
		 "//     Generated by the protocol buffer compiler.  DO NOT EDIT!\n"
		 "//     source: $file_name$\n"
		 "// </auto-generated>\n"
		 "#pragma warning disable 1591, 0612, 3021, 8981\n"
		 "#region Designer generated code\n"
		 "\n"
		 "using pb = global::Google.Protobuf;\n"
		 "using pbc = global::Google.Protobuf.Collections;\n"
		 "using pbr = global::Google.Protobuf.Reflection;\n"
		 "using scg = global::System.Collections.Generic;\n",
		 "file_name", r->file->name, NULL);
	if (*r->namespace_) {
		lp_print(printer, "namespace $namespace$ {\n", "namespace", r->namespace_, NULL);
		lp_indent(printer);
		lp_print(printer, "\n", NULL);
	}
	if (r->nrt_enabled)
		lp_print(printer, "#nullable enable annotations\n", NULL);
	lp_print(printer,
		 "/// <summary>Holder for reflection information generated from $file_name$</summary>\n"
		 "$access_level$ static partial class $reflection_class_name$ {\n"
		 "\n",
		 "file_name", r->file->name, "access_level", cs_class_access_level(r->options), "reflection_class_name",
		 r->reflection_classname, NULL);
	lp_indent(printer);
}

/* WriteGeneratedCodeInfo: the CLR type, property names, oneof names, nested enums, extensions
 * and nested types of a message, pre-ordered depth first, one per line. last: whether this is
 * the last message of its context (no trailing comma and newline). */
static void cs_reflection_write_generated_code_info(CsReflectionClassGen *r, const LpMessage *descriptor,
						    LpPrinter *printer, bool last)
{
	if (cs_is_map_entry_message(descriptor)) {
		lp_print(printer, "null, ", NULL);
		return;
	}
	/* Generated message type */
	lp_print(printer, "new pbr::GeneratedClrTypeInfo(typeof($type_name$), $type_name$.Parser, ", "type_name",
		 lp_csharp_class_name_message(descriptor), NULL);

	/* Fields */
	if (descriptor->n_fields > 0) {
		Buf fields = {0};
		for (int i = 0; i < descriptor->n_fields; i++) {
			if (i)
				buf_adds(&fields, "\", \"");
			buf_adds(&fields, cs_get_property_name(&descriptor->fields[i]));
		}
		lp_print(printer, "new[]{ \"$fields$\" }, ", "fields", buf_str(&fields), NULL);
	} else {
		lp_print(printer, "null, ", NULL);
	}

	/* Oneofs */
	if (descriptor->n_oneofs > 0) {
		Buf oneofs = {0};
		int n = 0;
		for (int i = 0; i < descriptor->n_oneofs; i++) {
			if (r->options->strip_nonfunctional_codegen && i >= descriptor->n_real_oneofs)
				/* Skip synthetic oneofs, which don't affect any actual behavior outside
				 * reflection. */
				break;
			if (n++)
				buf_adds(&oneofs, "\", \"");
			buf_adds(&oneofs, lp_csharp_underscores_to_camel_case(descriptor->oneofs[i].name, true, false));
		}
		if (!n)
			lp_print(printer, "null, ", NULL);
		else
			lp_print(printer, "new[]{ \"$oneofs$\" }, ", "oneofs", buf_str(&oneofs), NULL);
	} else {
		lp_print(printer, "null, ", NULL);
	}

	/* Nested enums */
	if (descriptor->n_enums > 0) {
		Buf enums = {0};
		for (int i = 0; i < descriptor->n_enums; i++) {
			if (i)
				buf_adds(&enums, "), typeof(");
			buf_adds(&enums, lp_csharp_class_name_enum(&descriptor->enums[i]));
		}
		lp_print(printer, "new[]{ typeof($enums$) }, ", "enums", buf_str(&enums), NULL);
	} else {
		lp_print(printer, "null, ", NULL);
	}

	/* Extensions */
	if (descriptor->n_extensions > 0) {
		Buf extensions = {0};
		for (int i = 0; i < descriptor->n_extensions; i++) {
			if (i)
				buf_adds(&extensions, ", ");
			buf_adds(&extensions, cs_get_full_extension_name(&descriptor->extensions[i]));
		}
		lp_print(printer, "new pb::Extension[] { $extensions$ }, ", "extensions", buf_str(&extensions), NULL);
	} else {
		lp_print(printer, "null, ", NULL);
	}

	/* Nested types */
	if (descriptor->n_nested > 0) {
		/* Need to specify array type explicitly here, as all elements may be null. */
		lp_print(printer, "new pbr::GeneratedClrTypeInfo[] { ", NULL);
		for (int i = 0; i < descriptor->n_nested; i++)
			cs_reflection_write_generated_code_info(r, &descriptor->nested[i], printer,
								i == descriptor->n_nested - 1);
		lp_print(printer, "}", NULL);
	} else {
		lp_print(printer, "null", NULL);
	}
	lp_print(printer, last ? ")" : "),\n", NULL);
}

static void cs_reflection_write_descriptor(CsReflectionClassGen *r, LpPrinter *printer)
{
	const LpFile *file = r->file;
	lp_print(printer,
		 "#region Descriptor\n"
		 "/// <summary>File descriptor for $file_name$</summary>\n"
		 "public static pbr::FileDescriptor Descriptor {\n"
		 "  get { return descriptor; }\n"
		 "}\n"
		 "private static pbr::FileDescriptor descriptor;\n"
		 "\n"
		 "static $reflection_class_name$() {\n",
		 "file_name", file->name, "reflection_class_name", r->reflection_classname, NULL);
	lp_indent(printer);
	lp_print(printer, "byte[] descriptorData = global::System.Convert.FromBase64String(\n", NULL);
	lp_indent(printer);
	lp_indent(printer);
	lp_print(printer, "string.Concat(\n", NULL);
	lp_indent(printer);

	const char *base64 = r->options->strip_nonfunctional_codegen ? "" : cs_file_descriptor_to_base64(file);
	size_t n = strlen(base64);
	while (n > 60) {
		lp_print(printer, "\"$base64$\",\n", "base64", xstrndup(base64, 60), NULL);
		base64 += 60;
		n -= 60;
	}
	lp_print(printer, "\"$base64$\"));\n", "base64", base64, NULL);
	lp_outdent(printer);
	lp_outdent(printer);
	lp_outdent(printer);

	/* Invoke InternalBuildGeneratedFileFrom() to build the file. */
	lp_print(printer, "descriptor = pbr::FileDescriptor.FromGeneratedCode(descriptorData,\n", NULL);
	lp_print(printer, "    new pbr::FileDescriptor[] { ", NULL);
	for (int i = 0; i < file->n_dependencies; i++) {
		if (r->options->strip_nonfunctional_codegen && lp_is_known_feature_proto(file->dependencies[i]->name))
			continue; /* Strip feature imports for editions codegen tests. */
		lp_print(printer, "$full_reflection_class_name$.Descriptor, ", "full_reflection_class_name",
			 lp_csharp_reflection_class_name(file->dependencies[i]), NULL);
	}
	lp_print(printer,
		 "},\n"
		 "    new pbr::GeneratedClrTypeInfo(",
		 NULL);
	/* Specify all the generated code information, recursively. */
	if (file->n_enums > 0) {
		lp_print(printer, "new[] {", NULL);
		for (int i = 0; i < file->n_enums; i++)
			lp_print(printer, "typeof($type_name$), ", "type_name", lp_csharp_class_name_enum(&file->enums[i]), NULL);
		lp_print(printer, "}, ", NULL);
	} else {
		lp_print(printer, "null, ", NULL);
	}
	if (file->n_extensions > 0) {
		Buf extensions = {0};
		for (int i = 0; i < file->n_extensions; i++) {
			if (i)
				buf_adds(&extensions, ", ");
			buf_adds(&extensions, cs_get_full_extension_name(&file->extensions[i]));
		}
		lp_print(printer, "new pb::Extension[] { $extensions$ }, ", "extensions", buf_str(&extensions), NULL);
	} else {
		lp_print(printer, "null, ", NULL);
	}
	if (file->n_messages > 0) {
		lp_print(printer, "new pbr::GeneratedClrTypeInfo[] {\n", NULL);
		lp_indent(printer);
		lp_indent(printer);
		lp_indent(printer);
		for (int i = 0; i < file->n_messages; i++)
			cs_reflection_write_generated_code_info(r, &file->messages[i], printer, i == file->n_messages - 1);
		lp_outdent(printer);
		lp_print(printer, "\n}));\n", NULL);
		lp_outdent(printer);
		lp_outdent(printer);
	} else {
		lp_print(printer, "null));\n", NULL);
	}
	lp_outdent(printer);
	lp_print(printer, "}\n", NULL);
	lp_print(printer, "#endregion\n\n", NULL);
}

/* ReflectionClassGenerator(file, options).Generate(printer) */
static void cs_reflection_class_generate(const LpFile *file, const CsOptions *options, LpPrinter *printer)
{
	CsReflectionClassGen r = {
		.file = file,
		.options = options,
		.namespace_ = lp_csharp_file_namespace(file),
		.reflection_classname = lp_csharp_reflection_class_unqualified_name(file),
		.extension_classname = lp_csharp_extension_class_unqualified_name(file),
		.nrt_enabled = cs_nrt_enabled(file),
	};
	cs_reflection_write_introduction(&r, printer);
	cs_reflection_write_descriptor(&r, printer);
	/* Close the class declaration. */
	lp_outdent(printer);
	lp_print(printer, "}\n", NULL);

	if (file->n_extensions > 0) {
		lp_print(printer,
			 "/// <summary>Holder for extension identifiers generated from the top level of $file_name$</summary>\n"
			 "$access_level$ static partial class $class_name$ {\n",
			 "access_level", cs_class_access_level(options), "class_name", r.extension_classname, "file_name",
			 file->name, NULL);
		lp_indent(printer);
		for (int i = 0; i < file->n_extensions; i++)
			cs_generate_extension_code(cs_create_field_generator(&file->extensions[i], -1, options), printer);
		lp_outdent(printer);
		lp_print(printer,
			 "}\n"
			 "\n",
			 NULL);
	}

	/* write children: Enums */
	if (file->n_enums > 0) {
		lp_print(printer, "#region Enums\n", NULL);
		for (int i = 0; i < file->n_enums; i++)
			cs_enum_generate(&file->enums[i], options, printer);
		lp_print(printer, "#endregion\n", NULL);
		lp_print(printer, "\n", NULL);
	}

	/* write children: Messages */
	if (file->n_messages > 0) {
		lp_print(printer, "#region Messages\n", NULL);
		for (int i = 0; i < file->n_messages; i++)
			cs_message_generate(&file->messages[i], options, printer);
		lp_print(printer, "#endregion\n", NULL);
		lp_print(printer, "\n", NULL);
	}

	if (*r.namespace_) {
		lp_outdent(printer);
		lp_print(printer, "}\n", NULL);
	}
	lp_print(printer, "\n", NULL);
	lp_print(printer, "#endregion Designer generated code\n", NULL);
}
