/* Port of Sources/protoc-gen-swift/FileGenerator.swift (with buf's extramoduleimports.patch). */

#define COMPATIBILITY_VERSION 2 /* Version.compatibilityVersion */

/* outputFilename */
static char *output_filename(const Options *o, const SwFile *file)
{
	PathParts parts = split_path(file->name);
	switch (o->output_naming) {
	case NAMING_FULL_PATH: return xcat(parts.dir, parts.base, ".pb.swift");
	case NAMING_PATH_TO_UNDERSCORES: return xcat(str_replace_all(parts.dir, "/", "_"), parts.base, ".pb.swift");
	case NAMING_DROP_PATH: return xcat(parts.base, ".pb.swift");
	}
	return NULL;
}

static void generate_version_check(SwPrinter *p, const Gen *g)
{
	sw_printf(p, "// If the compiler emits an error on this type, it is because this file\n"
		     "// was generated by a version of the `protoc` Swift plug-in that is\n"
		     "// incompatible with the version of SwiftProtobuf to which you are linking.\n"
		     "// Please ensure that you are building against the same version of the API\n"
		     "// that was used to generate this file.\n"
		     "fileprivate nonisolated struct _GeneratedWithProtocGenSwiftVersion: %sProtobufAPIVersionCheck {",
		  g->pfx);
	print_indented2(p, xfmt("struct _%d: %sProtobufAPIVersion_%d {}", COMPATIBILITY_VERSION, g->pfx, COMPATIBILITY_VERSION),
			xfmt("typealias Version = _%d", COMPATIBILITY_VERSION));
	sw_print(p, "}");
}

/* generateOutputFile(printer:errorString:) */
static void generate_output_file(Gen *g, SwPrinter *p)
{
	SwFile *file = g->file;
	const Options *o = g->opts;
	const char *swift_prefix = pb_str(file->options, 39);
	if (*swift_prefix && !sw_is_valid_swift_identifier(swift_prefix, false)) {
		g->error = xcat(file->name, " has an 'swift_prefix' that isn't a valid Swift identifier (", swift_prefix, ").");
		return;
	}
	sw_printf(p, "// DO NOT EDIT.\n"
		     "// swift-format-ignore-file\n"
		     "// swiftlint:disable all\n"
		     "//\n"
		     "// Generated by the Swift generator plugin for the protocol buffer compiler.\n"
		     "// Source: %s\n"
		     "//\n"
		     "// For information on using the generated types, please see the documentation:\n"
		     "//   https://github.com/apple/swift-protobuf/\n",
		  file->name);

	/* The comments at the top of the .proto file: on the edition or the syntax declaration. */
	PbMsg *comment_location = NULL;
	if (!o->experimental_strip_nonfunctional_codegen) {
		int32_t edition_path[] = {FDP_EDITION}, syntax_path[] = {FDP_SYNTAX};
		comment_location = sw_file_location(file, edition_path, 1);
		if (!comment_location)
			comment_location = sw_file_location(file, syntax_path, 1);
	}
	if (comment_location) {
		Str comments = sw_as_source_comment(comment_location, "///", "//");
		if (comments.n)
			sw_print_nl(p, comments, !str_has_suffix(comments, STR_LIT("\n\n")));
	}

	bool file_defines_types = file->enums.n || file->messages.n || file->extensions.n;
	bool has_imports = false;
	if (file_needs_foundation_import(file)) {
		const char *s = import_snippet(o);
		sw_printf(p, "#if canImport(FoundationEssentials)\n%s FoundationEssentials\n#else\n%s Foundation\n#endif", s, s);
		has_imports = true;
	}
	if (sw_is_bundled_proto(file)) {
		sw_printf(p, "// 'import %s' suppressed, this proto file is meant to be bundled in the runtime.",
			  sw_namer_swift_protobuf_module_name(g->namer));
		has_imports = true;
	} else if (file_defines_types) {
		sw_printf(p, "%s %s", import_snippet(o), sw_namer_swift_protobuf_module_name(g->namer));
		has_imports = true;
	}
	const char *needed_imports = compute_imports(g->namer);
	if (*needed_imports) {
		if (has_imports)
			sw_print_blank(p);
		sw_print(p, needed_imports);
		has_imports = true;
	}
	if (!file_defines_types) {
		if (has_imports)
			sw_print_blank(p);
		sw_print(p, "// This file contained no messages, enums, or extensions.");
		return;
	}
	if (o->extra_module_imports.n) {
		sw_print_blank(p);
		for (int i = 0; i < o->extra_module_imports.n; i++)
			sw_printf(p, "import %s\n", (const char *)o->extra_module_imports.v[i]);
	}
	sw_print_blank(p);
	generate_version_check(p, g);

	ExtensionSet extension_set = {g, {0}};
	extension_set_add(&extension_set, &file->extensions);
	Vec enums = {0}, messages = {0};
	for (int i = 0; i < file->enums.n; i++)
		vec_push(&enums, enum_gen(g, file->enums.v[i]));
	for (int i = 0; i < file->messages.n; i++)
		vec_push(&messages, message_gen(g, file->messages.v[i], &extension_set));

	for (int i = 0; i < enums.n; i++)
		enum_generate_main_enum(p, enums.v[i]);
	for (int i = 0; i < messages.n; i++)
		message_generate_main_struct(p, messages.v[i], NULL);

	if (extension_set.extensions.n) {
		PathParts parts = split_path(file->name);
		sw_print(p, "");
		sw_printf(p, "// MARK: - Extension support defined in %s%s.", parts.base, parts.suffix);
		extension_set_generate_message_swift_extensions(p, &extension_set);
		extension_set_generate_file_registry(p, &extension_set);
		extension_set_generate_declarations(p, &extension_set);
	}

	const char *package = file->package;
	bool needs_proto_package = *package && messages.n;
	if (needs_proto_package || enums.n || messages.n) {
		sw_print(p, "");
		sw_print(p, "// MARK: - Code below here is support for the SwiftProtobuf runtime.");
		if (needs_proto_package && !(o->experimental_hidden_names & HIDDEN_TYPES)) {
			sw_print(p, "");
			sw_printf(p, "fileprivate nonisolated let _protobuf_package = \"%s\"", package);
		}
		for (int i = 0; i < enums.n; i++)
			enum_generate_runtime_support(p, enums.v[i]);
		for (int i = 0; i < messages.n; i++)
			message_generate_runtime_support(p, messages.v[i], NULL);
	}
}
