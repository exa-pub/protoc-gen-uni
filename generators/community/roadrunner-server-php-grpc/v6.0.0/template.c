/* Ported from protoc_plugins/protoc-gen-php-grpc/php/template.go (roadrunner-server/grpc v6.0.0).
 * The text/template phpBody becomes the code of body() with the same output:
 *
 *	<?php
 *	# Generated by the protocol buffer compiler (roadrunner-server/grpc). DO NOT EDIT!
 *	# source: {{ .File.Name }}
 *	{{ $ns := .Namespace -}}
 *	{{if $ns.Namespace}}
 *	namespace {{ $ns.Namespace }};
 *	{{end}}
 *	use Spiral\RoadRunner\GRPC;
 *
 *	interface {{ .Service.Name | interface }} extends GRPC\ServiceInterface
 *	{
 *	    // GRPC specific service name.
 *	    public const NAME = "{{ resolve_name_const .File.Package .Service.Name }}";{{ "\n" }}
 *	{{- range $m := .Service.Method}}
 *	{{- $inName := name $ns $m.InputType }}
 *	{{- $outName := name $ns $m.OutputType }}
 *	    / **
 *	    * @param GRPC\ContextInterface $ctx
 *	    * @param {{ strip_slashes $inName }} $in
 *	    * @return {{ strip_slashes $outName }}
 *	    *
 *	    * @throws GRPC\Exception\InvokeException
 *	    * /
 *	    public function {{ $m.Name }}(GRPC\ContextInterface $ctx, {{ strip_slashes $inName }} $in): {{ strip_slashes $outName }};
 *	{{end -}}
 *	}
 *
 * (the comment delimiters of the PHP doc comment are spaced here). A function that panics (a nil
 * type name) fails execution with text/template's error, which body() panics with. */

/* Execution panics (errors of text/template and runtime errors) unwind with fail(). */
#define NIL_DEREF "runtime error: invalid memory address or nil pointer dereference"

/* generate php filename */
static Str filename(const PbMsg *file, Str name)
{
	Str ns = namespace(opt_str(file, FDP_PACKAGE), '/');
	Str phpNs = php_namespace(file);
	if (phpNs.p) {
		Buf b = {0};
		for (size_t i = 0; i < phpNs.n; i++)
			buf_addc(&b, phpNs.p[i] == '\\' ? '/' : phpNs.p[i]);
		ns = buf_view(&b);
	}
	if (!name.p)
		fail("%s", NIL_DEREF); /* *name */
	Buf b = {0};
	buf_add_str(&b, ns);
	buf_addc(&b, '/');
	identifier(&b, name, "interface");
	buf_adds(&b, ".php");
	return buf_view(&b);
}

/* printValue of a *string: the string, or "<nil>" (fmt.Fprint of a nil pointer) */
static void print_str(Buf *b, Str s)
{
	if (s.p)
		buf_add_str(b, s);
	else
		buf_adds(b, "<nil>");
}

/* strip_slashes: strings.ReplaceAll(name, `\\`, `\`) */
static void strip_slashes(Buf *b, Str name)
{
	for (size_t i = 0; i < name.n; i++) {
		buf_addc(b, name.p[i]);
		if (name.p[i] == '\\' && i + 1 < name.n && name.p[i + 1] == '\\')
			i++;
	}
}

/* {{ name $ns $m.<field> }} at line:column of phpBody: ns.resolve(name), which dereferences name */
static Str name_func(const ns *n, Str name, const char *at, const char *field)
{
	if (!name.p)
		fail("template: phpBody:%s: executing \"phpBody\" at <name $ns $m.%s>: error calling name: " NIL_DEREF,
		     at, field);
	return resolve(n, name);
}

/* generate php file body */
static Str body(const Request *req, const PbMsg *file, const PbMsg *service)
{
	const ns *n = newNamespace(req, file, service);
	Buf out = {0};
	buf_adds(&out, "<?php\n# Generated by the protocol buffer compiler (roadrunner-server/grpc). DO NOT EDIT!\n# source: ");
	print_str(&out, opt_str(file, FDP_NAME));
	buf_addc(&out, '\n');
	if (n->Namespace.n) {
		buf_adds(&out, "\nnamespace ");
		buf_add_str(&out, n->Namespace);
		buf_adds(&out, ";\n");
	}
	buf_adds(&out, "\nuse Spiral\\RoadRunner\\GRPC;\n\ninterface ");
	identifier(&out, opt_str(service, SDP_NAME), "interface"); /* not nil: filename() came first */
	buf_adds(&out, " extends GRPC\\ServiceInterface\n{\n    // GRPC specific service name.\n    public const NAME = \"");
	/* resolve_name_const */
	Str pkg = deref(opt_str(file, FDP_PACKAGE)), svc = deref(opt_str(service, SDP_NAME));
	if (pkg.n) {
		buf_add_str(&out, pkg);
		buf_addc(&out, '.');
	}
	buf_add_str(&out, svc);
	buf_adds(&out, "\";\n");
	for (int i = 0; i < pb_count(service, SDP_METHOD); i++) {
		const PbMsg *m = pb_msg_at(service, SDP_METHOD, i);
		Str inName = name_func(n, opt_str(m, MDP_INPUT_TYPE), "15:15", "InputType");
		Str outName = name_func(n, opt_str(m, MDP_OUTPUT_TYPE), "16:16", "OutputType");
		buf_adds(&out, "\n    /**\n    * @param GRPC\\ContextInterface $ctx\n    * @param ");
		strip_slashes(&out, inName);
		buf_adds(&out, " $in\n    * @return ");
		strip_slashes(&out, outName);
		buf_adds(&out, "\n    *\n    * @throws GRPC\\Exception\\InvokeException\n    */\n    public function ");
		print_str(&out, opt_str(m, MDP_NAME));
		buf_adds(&out, "(GRPC\\ContextInterface $ctx, ");
		strip_slashes(&out, inName);
		buf_adds(&out, " $in): ");
		strip_slashes(&out, outName);
		buf_adds(&out, ";\n");
		output_check(out.n);
	}
	buf_adds(&out, "}\n");
	return buf_view(&out);
}
