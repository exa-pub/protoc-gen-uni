/* Ported from internal/gen/template.go (protoc-gen-go-json v1.6.0). The two text/template texts
 * are expanded by hand: "{{-" trims the white space before an action, so the output of each
 * conditional block starts right after the preceding text. */

/* Options are the options to set for rendering the template. */
typedef struct {
	bool EnumsAsInts;
	bool EmitDefaults;
	bool EmitDefaultValues;
	bool OrigName;
	bool AllowUnknownFields;
	bool EmitScannerValuer;
} Options;

/* genStandaloneComments prints all leading comments for a FileDescriptorProto location identified
 * by the field number n. */
static void gen_standalone_comments(PgGeneratedFile *g, PgFile *f, int32_t n)
{
	GoSourceLocation loc = go_source_location_by_path(f->Desc, &n, 1);
	for (int i = 0; i < loc.n_detached; i++) {
		P(g, (PgComments){loc.detached[i]});
		P(g, "");
	}
	if (loc.leading.n) {
		P(g, (PgComments){loc.leading});
		P(g, "");
	}
}

static void w(PgGeneratedFile *g, const char *s) { pg_write(g, str_c(s)); }

/* headerTemplate */
static void header_template(PgGeneratedFile *g, PgFile *f, const Options *o)
{
	w(g, "\npackage ");
	w(g, f->GoPackageName);
	w(g, "\n\nimport (");
	if (o->EmitScannerValuer)
		w(g, "\n\t\"database/sql/driver\"\n\t\"fmt\"");
	w(g, "\n\n\t\"google.golang.org/protobuf/encoding/protojson\"\n)\n");
}

/* messageTemplate */
static void message_template(PgGeneratedFile *g, PgMessage *m, const Options *o)
{
	const char *name = m->GoIdent.GoName;
	w(g, "\n// MarshalJSON implements json.Marshaler\nfunc (msg *");
	w(g, name);
	w(g, ") MarshalJSON() ([]byte,error) {\n\treturn protojson.MarshalOptions {");
	if (o->EnumsAsInts)
		w(g, "\n\t\tUseEnumNumbers: true,");
	if (o->EmitDefaults)
		w(g, "\n\t\tEmitUnpopulated: true,");
	if (o->OrigName)
		w(g, "\n\t\tUseProtoNames: true,");
	if (o->EmitDefaultValues)
		w(g, "\n\t\tEmitDefaultValues: true,");
	w(g, "\n\t}.Marshal(msg)\n}\n\n// UnmarshalJSON implements json.Unmarshaler\nfunc (msg *");
	w(g, name);
	w(g, ") UnmarshalJSON(b []byte) error {\n\treturn protojson.UnmarshalOptions {");
	if (o->AllowUnknownFields)
		w(g, "\n\t\tDiscardUnknown: true,");
	w(g, "\n\t}.Unmarshal(b, msg)\n}");
	if (o->EmitScannerValuer) {
		w(g, "\n\n// Scan implements database/sql.Scanner\nfunc (msg *");
		w(g, name);
		w(g, ") Scan(src any) error {\n\tif msg == nil {\n\t\treturn fmt.Errorf(\"");
		w(g, name);
		w(g, ".Scan: nil receiver\")\n\t}\n\tif src == nil {\n\t\t*msg = ");
		w(g, name);
		w(g, "{}\n\t\treturn nil\n\t}\n\tvar b []byte\n\tswitch v := src.(type) {\n\tcase []byte:\n\t\tb = v\n\tcase "
		     "string:\n\t\tb = []byte(v)\n\tdefault:\n\t\treturn fmt.Errorf(\"");
		w(g, name);
		w(g, ".Scan: expected []byte or string, got %T\", src)\n\t}\n\treturn msg.UnmarshalJSON(b)\n}\n\n// Value "
		     "implements database/sql/driver.Valuer\nfunc (msg *");
		w(g, name);
		w(g, ") Value() (driver.Value, error) {\n\tif msg == nil {\n\t\treturn nil, nil\n\t}\n\tb, err := "
		     "msg.MarshalJSON()\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn string(b), nil\n}");
	}
	w(g, "\n");
}

/* applyMessages */
static void apply_messages(PgGeneratedFile *g, PgMessage **msgs, int n, const Options *o)
{
	for (int i = 0; i < n; i++) {
		PgMessage *m = msgs[i];
		if (m->Desc->is_map_entry)
			continue;
		message_template(g, m, o);
		apply_messages(g, m->Messages, m->nMessages, o);
	}
}

/* ApplyTemplate */
static void apply_template(PgGeneratedFile *g, PgFile *f, const Options *o)
{
	enum { syntaxFieldNumber = 12, packageFieldNumber = 2 };
	gen_standalone_comments(g, f, syntaxFieldNumber);
	P(g, "// Code generated by protoc-gen-go-json. DO NOT EDIT.");
	P(g, "// source: ", f->Desc->d.name);
	P(g, "");
	gen_standalone_comments(g, f, packageFieldNumber);
	header_template(g, f, o);
	apply_messages(g, f->Messages, f->nMessages, o);
}
