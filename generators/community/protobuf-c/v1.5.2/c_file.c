/* Port of protoc-gen-c/c_file.{h,cc} (protobuf-c v1.5.2): FileGenerator. The
 * ExtensionGenerators of the file (c_extension.cc) print nothing and are left out. */

static void file_generator_init(FileGenerator *g, const LpFile *file, const char *dllexport_decl)
{
	g->file = file;
	g->message_generators = xalloc(sizeof(MessageGenerator) * (size_t)(file->n_messages + 1));
	for (int i = 0; i < file->n_messages; i++)
		message_generator_init(&g->message_generators[i], &file->messages[i], dllexport_decl);
	g->enum_generators = xalloc(sizeof(EnumGenerator) * (size_t)(file->n_enums + 1));
	for (int i = 0; i < file->n_enums; i++)
		g->enum_generators[i] = (EnumGenerator){&file->enums[i], dllexport_decl};
	g->service_generators = xalloc(sizeof(ServiceGenerator) * (size_t)(file->n_services + 1));
	for (int i = 0; i < file->n_services; i++)
		service_generator_init(&g->service_generators[i], &file->services[i], dllexport_decl);
}

static void file_generate_header(FileGenerator *g, LpPrinter3 *printer)
{
	const LpFile *file = g->file;
	char *filename_ident = filename_identifier(file->name);
	const int min_header_version = 1003000;

	/* Generate top of header. */
	lp3_print(printer,
		  "/* Generated by the protocol buffer compiler.  DO NOT EDIT! */\n"
		  "/* Generated from: $filename$ */\n"
		  "\n"
		  "#ifndef PROTOBUF_C_$filename_identifier$__INCLUDED\n"
		  "#define PROTOBUF_C_$filename_identifier$__INCLUDED\n"
		  "\n"
		  "#include <protobuf-c/protobuf-c.h>\n"
		  "\n"
		  "PROTOBUF_C__BEGIN_DECLS\n"
		  "\n",
		  "filename", file->name, "filename_identifier", filename_ident, NULL);

	/* Verify the protobuf-c library header version is compatible with the protoc-gen-c version
	 * before going any further. */
	lp3_print(printer,
		  "#if PROTOBUF_C_VERSION_NUMBER < $min_header_version$\n"
		  "# error This file was generated by a newer version of protobuf-c which is "
		  "incompatible with your libprotobuf-c headers. Please update your headers.\n"
		  "#elif $protoc_version$ < PROTOBUF_C_MIN_COMPILER_VERSION\n"
		  "# error This file was generated by an older version of protobuf-c which is "
		  "incompatible with your libprotobuf-c headers. Please regenerate this file "
		  "with a newer version of protobuf-c.\n"
		  "#endif\n"
		  "\n",
		  "min_header_version", simple_itoa(min_header_version), "protoc_version",
		  simple_itoa(PROTOBUF_C_VERSION_NUMBER), NULL);

	for (int i = 0; i < file->n_dependencies; i++) {
		const LpFile *dependency = file->dependencies[i];
		if (!pbc_file_options(dependency)->no_generate)
			lp3_print(printer, "#include \"$dependency$.pb-c.h\"\n", "dependency", strip_proto(dependency->name),
				  NULL);
	}

	lp3_print(printer, "\n", NULL);

	/* Generate forward declarations of classes. */
	for (int i = 0; i < file->n_messages; i++)
		message_generate_struct_typedef(&g->message_generators[i], printer);

	lp3_print(printer, "\n", NULL);

	/* Generate enum definitions. */
	lp3_print(printer, "\n/* --- enums --- */\n\n", NULL);
	for (int i = 0; i < file->n_messages; i++)
		message_generate_enum_definitions(&g->message_generators[i], printer);
	for (int i = 0; i < file->n_enums; i++)
		enum_generate_definition(&g->enum_generators[i], printer);

	/* Generate class definitions. */
	lp3_print(printer, "\n/* --- messages --- */\n\n", NULL);
	for (int i = 0; i < file->n_messages; i++)
		message_generate_struct_definition(&g->message_generators[i], printer);

	for (int i = 0; i < file->n_messages; i++) {
		const PbcFileOptions *opt = pbc_file_options(file);
		message_generate_helper_function_declarations(&g->message_generators[i], printer,
							      opt->has_gen_pack_helpers, opt->gen_pack_helpers,
							      opt->gen_init_helpers);
	}

	lp3_print(printer, "/* --- per-message closures --- */\n\n", NULL);
	for (int i = 0; i < file->n_messages; i++)
		message_generate_closure_typedef(&g->message_generators[i], printer);

	/* Generate service definitions. */
	lp3_print(printer, "\n/* --- services --- */\n\n", NULL);
	for (int i = 0; i < file->n_services; i++)
		service_generate_main_h_file(&g->service_generators[i], printer);

	/* Declare extension identifiers: ExtensionGenerator::GenerateDeclaration prints nothing. */

	lp3_print(printer, "\n/* --- descriptors --- */\n\n", NULL);
	for (int i = 0; i < file->n_enums; i++)
		enum_generate_descriptor_declarations(&g->enum_generators[i], printer);
	for (int i = 0; i < file->n_messages; i++)
		message_generate_descriptor_declarations(&g->message_generators[i], printer);
	for (int i = 0; i < file->n_services; i++)
		service_generate_descriptor_declarations(&g->service_generators[i], printer);

	lp3_print(printer,
		  "\n"
		  "PROTOBUF_C__END_DECLS\n"
		  "\n\n#endif  /* PROTOBUF_C_$filename_identifier$__INCLUDED */\n",
		  "filename_identifier", filename_ident, NULL);
}

static void file_generate_source(FileGenerator *g, LpPrinter3 *printer)
{
	const LpFile *file = g->file;
	lp3_print(printer,
		  "/* Generated by the protocol buffer compiler.  DO NOT EDIT! */\n"
		  "/* Generated from: $filename$ */\n"
		  "\n"
		  "/* Do not generate deprecated warnings for self */\n"
		  "#ifndef PROTOBUF_C__NO_DEPRECATED\n"
		  "#define PROTOBUF_C__NO_DEPRECATED\n"
		  "#endif\n"
		  "\n"
		  "#include \"$basename$.pb-c.h\"\n",
		  "filename", file->name, "basename", strip_proto(file->name), NULL);

	const PbcFileOptions *opt = pbc_file_options(file);
	for (int i = 0; i < file->n_messages; i++)
		message_generate_helper_function_definitions(&g->message_generators[i], printer, opt->has_gen_pack_helpers,
							     opt->gen_pack_helpers, opt->gen_init_helpers);
	for (int i = 0; i < file->n_messages; i++)
		message_generate_message_descriptor(&g->message_generators[i], printer, opt->gen_init_helpers);
	for (int i = 0; i < file->n_enums; i++)
		enum_generate_enum_descriptor(&g->enum_generators[i], printer);
	for (int i = 0; i < file->n_services; i++)
		service_generate_c_file(&g->service_generators[i], printer);
}
